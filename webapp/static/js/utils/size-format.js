/**
 * עיצוב גדלי קבצים לתצוגה — מקור אמת אחד לצד הלקוח.
 *
 * משותף ל-compare, global_search, live-preview, json-formatter, repo-browser
 * ו-file-form-manager. לפני הקובץ הזה לכל אחד מהם היה מימוש משלו, ושישתם
 * נבדלו זה מזה: תקרת יחידות שונה (MB / GB / TB), רווח לפני היחידה בחלק ובלי
 * בחלק, ועיגול שונה. שלושה באגים אמיתיים נבעו מזה — ``3584KB`` במקום
 * ``3.5 MB``, ``2048 MB`` במקום ``2 GB``, ו-``3 undefined`` מעל טרה-בייט.
 *
 * התאום שלו בצד השרת הוא ``webapp/size_format.py``, ושניהם חייבים להחזיר
 * בדיוק אותו דבר. ``tests/test_file_size_display.py`` מריץ את שניהם על אותו וקטור
 * ערכים ומשווה — כי "כתובים אותו דבר" אינו ראיה שהם מתנהגים אותו דבר.
 *
 * נטען גלובלית מ-``base.html``, כמו ``utils/animations.js``.
 */
(function () {
  'use strict';

  /** סדר היחידות. האחרונה היא גם התקרה: מעליה הערך פשוט גדל. */
  var UNITS = ['B', 'KB', 'MB', 'GB', 'TB'];

  /** LRI פותח קטע שנקרא שמאל-לימין, PDI סוגר אותו. */
  var LRI = '⁦';
  var PDI = '⁩';

  // ─────────────────────────────────────────────────────────────────────
  // למה הערך עטוף בתווי בידוד — זה לא קישוט.
  //
  // "105 KB" בתוך טקסט בעברית **מתהפך על המסך** ל-"KB 105". אלגוריתם ה-bidi
  // רואה מספר, ואחריו רווח ניטרלי, ואחריו מילה לטינית. רווח ניטרלי בין מספר
  // למילה לטינית אינו מדביק אותם — הוא נופל לכיוון הפסקה, כלומר לעברית,
  // והמחרוזת נשברת לשני קטעים שמסודרים מימין לשמאל.
  //
  // נמדד ב-Chromium: בלי בידוד "KB" נוחת ב-x=325 ו-"105" ב-x=350. עם בידוד
  // "105" ב-x=325 ו-"KB" ב-x=359. תווי הבידוד אינם מוסיפים רוחב.
  //
  // **למה בתוך המחרוזת ולא ב-dir="ltr" על האלמנט:** כי לא לכל גודל יש אלמנט
  // משלו. ``file-form-manager.js`` בונה "x גדול מדי (מקסימום 2 MB)" כמחרוזת
  // אחת, ו-``live-preview.js`` מצרף שלושה שדות ל-``textContent`` יחיד. שם אין
  // על מה לתלות dir. בידוד בתוך הערך נוסע איתו לכל הקשר.
  //
  // המשמעות למי שקורא את הערך: ``indexOf('105 KB')`` עדיין עובד, השוואת
  // שוויון מדויקת לא. ראו ``tests/test_size_format_bidi_browser.py``.
  // ─────────────────────────────────────────────────────────────────────

  /**
   * מספר לתצוגה: ספרה אחת אחרי הנקודה, בלי ".0" מיותר.
   * 105.0 ← "105", 27.94 ← "27.9", 1.25 ← "1.3".
   *
   * **למה העיגול כתוב ביד ולא toFixed(1):** כי התאום בפייתון היה חייב להסכים
   * איתו, ושתי ברירות המחדל אינן מסכימות. (1.25).toFixed(1) מחזיר "1.3" (חצי
   * כלפי מעלה) ו-f"{1.25:.1f}" בפייתון מחזיר "1.2" (חצי לזוגי). הפער נמדד על
   * קובץ של 1280 בתים — גודל אמיתי לגמרי — ולכן אותו קובץ היה מוצג "1.2 KB"
   * מהשרת ו-"1.3 KB" מהדפדפן.
   *
   * כאן ובפייתון מחושב אותו דבר באותן פעולות על אותם doubles: כפל ב-10,
   * חיבור חצי, עיגול כלפי מטה. חצי תמיד עולה, ושתי השפות מגיעות לאותה תוצאה
   * כי הן מבצעות בדיוק את אותו רצף.
   */
  function formatSizeNumber(value) {
    var number = Number(value);
    if (!isFinite(number)) {
      number = 0;
    }
    var negative = number < 0;
    var tenths = Math.floor(Math.abs(number) * 10 + 0.5);
    var whole = Math.floor(tenths / 10);
    var frac = tenths - whole * 10;
    var text = frac === 0 ? String(whole) : whole + '.' + frac;
    return negative && tenths ? '-' + text : text;
  }

  /**
   * גודל בבייטים ← מחרוזת מוכנה לתצוגה, עטופה בבידוד דו-כיווני.
   * למשל "27.9 KB" או "582 B".
   *
   * ערך חסר או לא-סופי נחשב 0, ולא מייצר "NaN undefined" כמו קודם.
   */
  function formatFileSize(sizeBytes) {
    var size = Number(sizeBytes);
    if (!isFinite(size)) {
      size = 0;
    }
    for (var i = 0; i < UNITS.length; i++) {
      if (size < 1024 || i === UNITS.length - 1) {
        return LRI + formatSizeNumber(size) + ' ' + UNITS[i] + PDI;
      }
      size /= 1024;
    }
    // לא מגיעים לכאן: הלולאה תמיד מחזירה ביחידה האחרונה
    return LRI + formatSizeNumber(size) + ' ' + UNITS[UNITS.length - 1] + PDI;
  }

  if (typeof window !== 'undefined') {
    window.SizeFormat = {
      UNITS: UNITS,
      LRI: LRI,
      PDI: PDI,
      formatSizeNumber: formatSizeNumber,
      formatFileSize: formatFileSize,
    };
  }
})();
