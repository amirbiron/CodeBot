"""עיצוב גדלי קבצים לתצוגה — מקור אמת אחד לוובאפ.

שני כללים, ושניהם נולדו מבאג אמיתי:

**1. ספרה אחת אחרי הנקודה, ורק אם היא אומרת משהו.** ``105.0 KB`` ו-``582.0 B``
מוסיפים תו לכל כרטיס קובץ בלי להוסיף מידע, ו-``27.9 KB`` כן — ולכן החיתוך הוא
של ``.0`` בלבד ולא של כל השבר.

**2. הערך תמיד נקרא בסדר לטיני, בכל הקשר.** ראו ``BIDI_ISOLATION`` למטה.

המודול הזה הוא עלה: הוא אינו מייבא דבר מהוובאפ, ולכן אפשר לייבא אותו מכל מקום
בלי מעגל ייבוא. הוא נוצר אחרי שהכלל היה משוכפל בין ``webapp/app.py`` ל-
``webapp/collections_api.py``, ושתי העותקים היו יכולים להיסחף זה מזה.

התאום שלו בצד הלקוח הוא ``webapp/static/js/utils/size-format.js``, ושניהם
חייבים להחזיר בדיוק אותו דבר — ``tests/test_file_size_display.py`` אוכף זאת בהרצה
של שניהם על אותו וקטור ערכים.
"""

from __future__ import annotations

import math

#: סדר היחידות. האחרונה היא גם התקרה: מעליה הערך פשוט גדל.
UNITS: tuple[str, ...] = ("B", "KB", "MB", "GB", "TB")

#: LRI (U+2066) פותח קטע שנקרא שמאל-לימין, ו-PDI (U+2069) סוגר אותו.
LRI: str = "⁦"
PDI: str = "⁩"

BIDI_ISOLATION = """למה הערך עטוף בתווי בידוד — זה לא קישוט.

``"105 KB"`` בתוך פסקה בעברית **מתהפך על המסך** ל-``KB 105``. הסיבה היא
אלגוריתם ה-bidi: ``105`` הוא מספר, ``KB`` היא מילה לטינית, והרווח ביניהם
ניטרלי. רווח ניטרלי בין מספר למילה לטינית אינו מדביק אותם — הוא נופל לכיוון
הפסקה, כלומר לעברית, והמחרוזת נשברת לשני קטעים שמסודרים מימין לשמאל.

נמדד ב-Chromium: בלי בידוד ``KB`` נוחת ב-x=325 ו-``105`` ב-x=350, כלומר
היחידה משמאל למספר. עם בידוד ``105`` ב-x=325 ו-``KB`` ב-x=359. תווי הבידוד
אינם מוסיפים רוחב (נמדד: הפרש 0.02px, רעש תת-פיקסל).

**למה בתוך המחרוזת ולא ב-CSS או ב-``dir="ltr"`` על האלמנט:** כי לא לכל גודל
יש אלמנט משלו. ``webapp/app.py`` בונה ``"הקובץ גדול מדי לתצוגה (105 KB)"``
כמחרוזת אחת, ו-``file-form-manager.js`` בונה ``"x גדול מדי (מקסימום 2 MB)"``
באותה צורה. שם אין על מה לתלות ``dir``. בידוד בתוך הערך עצמו נוסע איתו לכל
הקשר — Jinja, ``textContent``, ``innerHTML``, JSON — ולכן הוא הפתרון היחיד
שמכסה את כולם.

הבדיקה שמוכיחה את זה היא בדיקת דפדפן, לא unit: סדר bidi הוא משהו שהדפדפן
אוכף ושרת לא רואה. ראו ``tests/test_size_format_bidi_browser.py``.
"""


def format_size_number(value: float) -> str:
    """מספר לתצוגה: ספרה אחת אחרי הנקודה, בלי ``.0`` מיותר.

    ``105.0`` ← ``"105"``, ``27.94`` ← ``"27.9"``, ``1.25`` ← ``"1.3"``.

    **למה העיגול כתוב ביד ולא ``f"{value:.1f}"``:** כי התאום ב-JS היה חייב
    להסכים איתו, ושתי ברירות המחדל אינן מסכימות. ``f"{1.25:.1f}"`` מחזיר
    ``"1.2"`` (חצי לזוגי) ו-``(1.25).toFixed(1)`` מחזיר ``"1.3"`` (חצי כלפי
    מעלה). הפער נמדד על קובץ של 1280 בתים — גודל אמיתי לגמרי — ולכן אותו
    קובץ היה מוצג ``1.2 KB`` מהשרת ו-``1.3 KB`` מהדפדפן.

    כאן וב-JS מחושב אותו דבר באותן פעולות על אותם doubles: כפל ב-10, חיבור
    חצי, עיגול כלפי מטה. כלומר חצי תמיד עולה, ושתי השפות מגיעות לאותה תוצאה
    כי הן מבצעות בדיוק את אותו רצף.

    המכפלה בטוחה בטווח הרלוונטי: גם אקסה-בייט נותן ``tenths`` בסדר גודל של
    מיליונים, רחוק מהגבול שבו ``Number`` של JS מאבד דיוק על שלמים.
    """
    number = float(value)
    if not math.isfinite(number):
        number = 0.0
    negative = number < 0
    tenths = int(math.floor(abs(number) * 10.0 + 0.5))
    whole, frac = divmod(tenths, 10)
    text = str(whole) if frac == 0 else f"{whole}.{frac}"
    return f"-{text}" if negative and tenths else text


def format_file_size(size_bytes: float | int) -> str:
    """גודל בבייטים ← מחרוזת מוכנה לתצוגה, עטופה בבידוד דו-כיווני.

    למשל ``27.9 KB`` או ``582 B``. המחרוזת המוחזרת נפתחת ב-LRI ונסגרת ב-PDI,
    ולכן ``"105 KB" in result`` עדיין נכון, אבל השוואת שוויון מדויקת אינה.
    ראו ``BIDI_ISOLATION``.

    ערך לא-סופי נחשב 0. בלי זה ``nan`` היה נופל דרך כל היחידות ומגיע כ-
    ``"nan TB"``, ואותו כלל קיים גם בתאום ה-JS כדי ששניהם יישארו זהים.
    """
    size = float(size_bytes)
    if not math.isfinite(size):
        size = 0.0
    for unit in UNITS:
        if size < 1024.0 or unit == UNITS[-1]:
            return f"{LRI}{format_size_number(size)} {unit}{PDI}"
        size /= 1024.0
    # לא מגיעים לכאן: הלולאה תמיד מחזירה ביחידה האחרונה
    return f"{LRI}{format_size_number(size)} {UNITS[-1]}{PDI}"
