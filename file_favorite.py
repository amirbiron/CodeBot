"""סימון מועדף — מצב של **קובץ**, לא של מסמך גרסה.

ב-Ck כל גרסה של קובץ היא מסמך נפרד ב-``code_snippets``, וסימון המועדף (``is_favorite`` ו-``favorited_at``) נשמר על כל מסמך. לכן שני כללים חייבים להחזיק יחד, והם הסיבה שהמודול קיים:

1. **קריאה:** קובץ הוא מועדף אם **איזושהי** גרסה פעילה שלו מסומנת — הכלל של ``Repository.is_favorite``. רשימת המועדפים בוובאפ מקבצת לפיו (``_latest_version_per_file_stages`` עם ``favorites_only``).
2. **כתיבה:** כל מסמך גרסה חדש יורש את הסימון, אחרת העריכה הבאה מוציאה את הקובץ מהמועדפים או משאירה אותו שם עם גרסה ישנה. זה מה ש-:func:`favorite_fields_for_new_version` קובע, וכל מסלול שכותב גרסה קורא לה.

**למה פונקציה אחת ולא עותק בכל כותב.** יש שבעה מסלולים שכותבים גרסה, וב-23.9.2026 נמצאו חמישה מהם בונים את המסמך ביד בלי הסימון — עריכה, העלאה, שמירת מדריך משותף ו-Incident Story ב-``webapp/app.py``, ושמירה מאוסף משותף ב-``webapp/collections_api.py``. שני האחרים החזיקו כל אחד עותק משלו של הכלל. השומר המבני ב-``tests/test_mcp_description_age.py`` (``_VERSION_WRITERS``) מוודא שכל כותב מזכיר את הפונקציה, ו-``tests/test_favorite_is_a_file_state.py`` בודק כל כותב בהתנהגות.

המודול טהור בכוונה — בלי מסד, בלי Flask ובלי קונפיג — כמו ``file_dates.py`` ו-``file_description.py``, ומאותה סיבה: שכבת המסד והוובאפ מחזיקות חיבורים נפרדים, ושתיהן חייבות לייבא את אותו כלל ישירות.
"""
from __future__ import annotations

from typing import Any, Dict

__all__ = ["favorite_fields_for_new_version"]


def favorite_fields_for_new_version(*previous_docs: Any) -> Dict[str, Any]:
    """השדות שמסמך גרסה חדש כותב כדי שהקובץ יישאר מועדף — או יישאר לא מועדף.

    המועמדים הם המסמכים שהגרסה החדשה נגזרת מהם, מהקרוב לרחוק: קודם הגרסה הפעילה האחרונה של הקובץ, ואחריה, כשיש, המסמך שממנו נפתחה העריכה או השחזור. **הראשון שמסומן קובע**, ו-``favorited_at`` נלקח ממנו — הרגע שבו הקובץ סומן, ולא רגע הכתיבה.

    **רק ``True`` בוליאני הוא סימון.** השאילתות על המועדפים מתאימות ``is_favorite: True``, ומונגו לא ממירה טיפוסים בהשוואה: נבדק מול MongoDB 8.0.32 ב-23.9.2026, והתנאי הזה לא תפס ``1`` ולא ``"yes"``. ערכים כאלה היו נראים מסומנים כאן ולא מסומנים בכל רשימה.

    כשאף מועמד אינו מסומן, מוחזר סימון שלילי **מפורש** ולא מילון ריק: הגרסה החדשה מחליטה על המצב שלה בזמן הכתיבה, ולא משאירה אותו לפרשנות של שדה חסר. זו גם הצורה ש-``scripts/cleanup_repo_tags.py`` משלים למסמכים בלי השדה. מאחר שהשאילתות מתאימות רק ``True``, ``False`` ושדה חסר נראים בהן אותו דבר — הבחירה משנה את מה שכתוב במסמך, לא תוצאה.
    """
    for doc in previous_docs:
        if isinstance(doc, dict) and doc.get("is_favorite") is True:
            return {"is_favorite": True, "favorited_at": doc.get("favorited_at")}
    return {"is_favorite": False, "favorited_at": None}
