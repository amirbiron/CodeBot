"""סימון מועדף — מצב של **קובץ**, לא של מסמך גרסה.

ב-Ck כל גרסה של קובץ היא מסמך נפרד ב-``code_snippets``, וסימון המועדף (``is_favorite`` ו-``favorited_at``) נשמר על כל מסמך. לכן שני כללים חייבים להחזיק יחד, והם הסיבה שהמודול קיים:

1. **קריאה:** קובץ הוא מועדף אם **איזושהי** גרסה פעילה שלו מסומנת — הכלל של ``Repository.is_favorite``. רשימת המועדפים בוובאפ מקבצת לפיו (``_latest_version_per_file_stages`` עם ``favorites_only``).
2. **כתיבה:** כל מסמך גרסה חדש יורש את המצב של **הקובץ**, לפי אותו כלל בדיוק. זה מה ש-:func:`favorite_fields_for_new_version` קובע, וכל מסלול שכותב גרסה קורא לה.

**למה הכתיבה שואלת את כל הגרסאות ולא את האחרונה.** בגרסה הראשונה של הכלל הגרסה החדשה ירשה מהגרסה האחרונה בלבד. בקובץ שרק גרסה ישנה שלו מסומנת — מצב שנמצא בפרודקשן בשני קבצים — העריכה הבאה כתבה גרסה לא מסומנת, בזמן שהרשימה המשיכה להציג את הקובץ כמועדף בזכות הגרסה הישנה. שני הכללים ענו תשובות שונות על אותה שאלה. כשהכתיבה שואלת בדיוק את מה שהקריאה שואלת, מצב כזה מתאחה בכתיבה הבאה במקום להימשך.

**למה פונקציה אחת ולא עותק בכל כותב.** יש שבעה מסלולים שכותבים גרסה, וב-23.9.2026 נמצאו חמישה מהם בונים את המסמך ביד בלי הסימון — עריכה, העלאה, שמירת מדריך משותף ו-Incident Story ב-``webapp/app.py``, ושמירה מאוסף משותף ב-``webapp/collections_api.py``. שני האחרים החזיקו כל אחד עותק משלו של הכלל, ועוד עותק ישב ב-``Repository.save_file`` וקרא את הגרסה האחרונה דרך ``get_latest_version`` — כלומר מהקאש, שם סימון שכבר הוסר יכול היה לחזור לחיים. השומר המבני ב-``tests/test_mcp_description_age.py`` (``_VERSION_WRITERS``) מוודא שכל כותב מזכיר את הפונקציה, ו-``tests/test_favorite_is_a_file_state.py`` בודק כל כותב בהתנהגות.

**המודול אינו מחזיק חיבור:** הקורא מעביר את האוסף שלו, כמו ב-``file_deletion.py`` ומאותה סיבה — הוובאפ ושכבת המסד מחזיקים חיבורים נפרדים, ושניהם חייבים להריץ את אותה שאילתה. אין כאן Flask ואין קונפיג.

**ערוץ הכשל: זריקה.** שגיאת מסד עולה לקורא ואינה מתורגמת ל"לא מועדף": גרסה שנכתבת עם סימון שגוי היא בדיוק הכשל השקט שהמודול קיים כדי למנוע. וקריאה בלי שם קובץ היא שגיאה של הקורא, ולכן ``ValueError`` ולא תשובה.
"""
from __future__ import annotations

from typing import Any, Dict

__all__ = ["favorite_fields_for_new_version"]


def favorite_fields_for_new_version(collection: Any, user_id: Any, *file_names: Any) -> Dict[str, Any]:
    """השדות שמסמך גרסה חדש כותב — לפי המצב של הקובץ ברגע הכתיבה.

    הקובץ מועדף אם איזושהי גרסה **פעילה** שלו מסומנת; גרסה בסל אינה נספרת, כי קובץ חדש שקיבל שם ממוחזר אינו אמור לרשת מקובץ שנמחק. ``favorited_at`` הוא הסימון האחרון בקובץ, כמו בשורה שרשימת המועדפים מציגה (``$max`` שם, מיון יורד כאן).

    ``file_names`` הוא שם הקובץ שהגרסה נכתבת אליו, ובעריכה ששינתה את השם — גם השם שממנו היא יצאה. כך קובץ מועדף שמשנים לו שם לא מאבד את הסימון, וקובץ שמצטרפים אליו בשם קיים לא נשאר עם גרסה אחרונה לא מסומנת.

    השאילתה נקראת **לפני** שהגרסה החדשה נכתבת, ולכן היא רואה רק את הגרסאות הקיימות. היטלה על שני השדות בלבד — אין סיבה למשוך את גוף הקובץ בשביל בוליאני.

    **רק ``True`` בוליאני הוא סימון.** השאילתה מתאימה ``is_favorite: True``, ומונגו לא ממירה טיפוסים בהשוואה: נבדק מול MongoDB 8.0.32 ב-23.9.2026, והתנאי הזה לא תפס ``1`` ולא ``"yes"``. הבדיקה החוזרת על המסמך שחזר מוודאת את אותו דבר גם מול אוסף שאינו מונגו.

    כשאין גרסה מסומנת, מוחזר סימון שלילי **מפורש** ולא מילון ריק: הגרסה החדשה מחליטה על המצב שלה בזמן הכתיבה, ולא משאירה אותו לפרשנות של שדה חסר. זו גם הצורה ש-``scripts/cleanup_repo_tags.py`` משלים למסמכים בלי השדה.
    """
    names = [name for name in dict.fromkeys(file_names) if name]
    if not names:
        raise ValueError("favorite_fields_for_new_version: file name is required")
    marked = collection.find_one(
        {"user_id": user_id, "file_name": {"$in": names}, "is_active": True, "is_favorite": True},
        {"_id": 0, "is_favorite": 1, "favorited_at": 1},
        sort=[("favorited_at", -1)],
    )
    if isinstance(marked, dict) and marked.get("is_favorite") is True:
        return {"is_favorite": True, "favorited_at": marked.get("favorited_at")}
    return {"is_favorite": False, "favorited_at": None}
