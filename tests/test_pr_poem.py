def test_an_http_error_message_names_the_status_and_hides_the_key(poem, monkeypatch):
    """הודעת הכשל נבנית מגוף התשובה, ולכן סוד שחזר בגוף מוחלף ב-``***`` לפני שהוא מודפס."""

    def refuse(request, timeout):
        body = io.BytesIO(json.dumps({"error": {"message": f"bad key {API_KEY}"}}).encode())
        raise urllib.error.HTTPError(request.full_url, 401, "Unauthorized", {}, body)

    monkeypatch.setattr(poem.urllib.request, "urlopen", refuse)

    with pytest.raises(poem.PoemError) as caught:
        poem.call_anthropic(API_KEY, {"model": "m"})

    message = str(caught.value)
    assert "HTTP 401" in message and "/v1/messages" in message
    assert API_KEY not in message and "***" in message
