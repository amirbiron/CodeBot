class FakeHttp:
    """מחליף את ``http_json``. עונה לפי ``(method, url)``, ורושם כל קריאה.

    תשובה שהיא פונקציה מקבלת את גוף הבקשה — כך תגובה שפורסמה חוזרת עם הגוף שנשלח, כמו ב-GitHub.
    """

    def __init__(self, responses: Dict[Tuple[str, str], Any]) -> None:
        self.responses = responses
        self.calls: List[Dict[str, Any]] = []

    def __call__(self, method, url, headers, payload, timeout, secrets):
        self.calls.append({"method": method, "url": url, "headers": dict(headers), "payload": payload})
        if (method, url) not in self.responses:
            raise AssertionError(f"קריאה שהטסט לא ציפה לה: {method} {url}")
        answer = self.responses[(method, url)]
        return answer(payload) if callable(answer) else answer

    def urls(self, method: str) -> List[str]:
        return [call["url"] for call in self.calls if call["method"] == method]


