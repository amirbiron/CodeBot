"""תקרה על מספר הסימבולים, משותפת לשלושת הסורקים.

**מה זה מונע, בשפה פשוטה:** קלט קטן שקונה עבודה גדולה. ``"<a>"`` שחוזר
מיליון פעם הוא 3.00MB, ואין לו אף ``id`` — כלומר הוא אינו מייצר **אף
שורה** במפה, אבל כל תגית נדחפת למחסנית וממתינה לסוגר שלא יבוא. נמדד:
122.5MB בלי התקרה ו-6.1MB איתה. ``"a{"`` שחוזר מיליון וחצי פעם, גם הוא
3.00MB, נמדד ב-363.0MB בלי התקרה ו-6.0MB איתה. בשני המקרים הקובץ נכנס
בנוחות לתקרת ה-10MB של ``RANGE_READ_MAX_BYTES``, כלומר אין דבר לפניה
שיעצור אותו.

**ולמה זה חשוב במיוחד כאן:** ``get_repo_file`` היא פונקציה סינכרונית,
וה-SDK של MCP קורא לה ``return fn(**arguments)`` בלי ``to_thread`` —
אומת בקוד ה-SDK המותקן, ב-
``mcp/server/fastmcp/utilities/func_metadata.py``. כלומר בקשה אחת כזאת
אינה מאיטה את עצמה בלבד; היא נועלת את לולאת האירועים לכל השאר.

**התקרה יושבת בסורקים ולא במנתב, וזה נמדד ולא הוכרע בטעם.** על
``".a{}"`` שחוזר 200,000 פעם (0.80MB): בדיקת אורך במנתב, אחרי שהסורק
סיים, הגיעה ל-48.6MB — בזמן שעצירה בתוך הסורק עצרה ב-12.2MB. במנתב
הרשימה כבר נבנתה במלואה והנזק כבר נעשה; סינון של פלט אינו חסימה של
עבודה.

**ולמה מודול אחות ולא מקום אחר**, לפי התקדים שנקבע ל-``_lines.py``:
ה-docstring של ``__init__.py`` אוסר קוד רץ בחבילה, וייבוא לרוחב מסורק
שכן היה יוצר תלות בין סורקים. הגיון שמשותף לכמה סורקים גר במודול משלו.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Any

#: מקסימום סימבולים לקובץ, ומעליו הסריקה נעצרת. **המספר נמדד ולא נבחר
#: כי הוא נראה עגול**, ושתי המדידות הן אלה:
#:
#: הראשונה — השיא שהתקרה **מרשה**, נמדד על תשע צורות קלט שכל אחת ממלאת
#: מכל אחר: **18.4MB במקרה הגרוע**, מול 24.3MB עד 363.0MB שנמדדו על
#: אותן צורות בלי התקרה. הגרועה שבהן היא מעבר העץ בפייתון (18.4MB),
#: ואחריה CSS שממלא את השורות ואת המחסנית יחד — 49,999 בכל אחת —
#: ב-18.2MB. הצורה המשולבת בין ``html`` ל-``css`` באותו קובץ ירדה
#: מ-18.8MB ל-12.2MB ברגע שהתקציב נעשה אחד ולא אחד לכל בלוק.
#:
#: **ומה שהיא אינה חוסמת, כדי שלא ייקרא כאן יותר ממה שכתוב:**
#: ``ast.parse`` בסורק הפייתון מקצה את כל העץ **לפני** שהמעבר מתחיל,
#: ולכן התקרה אינה נוגעת בו — נמדד 166.2MB על קובץ של 1.13MB עם 60,000
#: הגדרות, זהה בדיוק עם התקרה ובלעדיה. זו תכונה קיימת של אותו מסלול
#: ולא של המכל, והיא ממצא בפני עצמו. מה שהתקרה כן עושה שם: המעבר עוצר
#: על 50,000 במקום לבנות 60,000 שורות מעל העץ.
#:
#: השנייה — היחס לקובץ אמיתי. הצפוף בריפו הזה הוא ``webapp/app.py`` עם
#: 526 סימבולים, כלומר התקרה היא **פי 95** ממנו; ``base.html``, הגדול
#: בתבניות, מגיע ל-503 — אחוז אחד מהתקרה. כלומר קובץ אמת אינו מתקרב
#: לכאן, וכל מי שכן מגיע הוא קלט שנבנה בכוונה או פלט של מחשב.
#:
#: **מי שמשנה את המספר צריך למדוד מחדש את שתיהן.** העלאה בלי המדידה
#: הראשונה מחזירה את מחלקת הכשל; הורדה בלי השנייה חוסמת קובץ אמיתי.
MAX_SYMBOLS = 50_000


class TooManySymbols(Exception):
    """הקובץ מייצר יותר סימבולים ממה שהמפה הזאת ממפה.

    **חריגה ולא ערך החזרה, וזה הכיוון ההפוך של K11.** "עצור" כערך דורש
    בדיקה בכל אתר קריאה — שש לולאות בשלושת הסורקים — וכשל בדיקה **בודד**
    פירושו שהסריקה ממשיכה כאילו כלום. חריגה נכשלת בקול במקום להיבלע.

    **ומי שתופס אותה חייב לתפוס אותה בלבד.** ``except Exception`` באחת
    הרמות בדרך יבלע כל באג אחר בסורק ויחזיר "אין אאוטליין" על קובץ תקין
    לגמרי — וזה K11 בדיוק. שלוש התפיסות במסלול הזה כתובות
    ``except _ceiling.TooManySymbols`` ולא רחב מזה. וההורשה כאן היא
    מ-``Exception`` ישירות ולא מחריגת ספריית תקן, כדי שתפיסה צרה לא
    תוכל להתנגש בשגיאה אמיתית.
    """


class Capped(list[Any]):
    """רשימה שמסרבת לגדול מעל ``MAX_SYMBOLS``.

    **מכל ולא בדיקת אורך בכל אתר.** ב-``html.py`` יש שלושה-עשר אתרי
    הוספה לרשימת השורות — ``append`` בשורות 190, 193, 261, 266, 273,
    317, 324, 354, 359, 682, 719, 764 ו-``extend`` בשורה 318. שלושה-עשר
    בדיקות זהות הן בדיוק מה שאפשר לשכוח באתר הארבעה-עשר, בלי שאף טסט
    יראה. עם המכל אין אף נגיעה באתרי ההוספה, ואתר חדש שייכתב מחר מכוסה
    מהרגע הראשון.

    **תת-מחלקה של ``list`` ולא מחלקה חדשה**, כי ``mcp_server/outline.py``
    דורש ``isinstance(result["symbols"], list)`` ופוסל צורה אחרת
    כ"מחוץ לחוזה". וגם ``sort``, ``len`` ו-``json.dumps`` בהמשך המסלול
    עובדים בלי לדעת שהמכל קיים.

    ``append`` מקבלת ארגומנט positional-only, כמו ב-``list``, אחרת
    ``mypy`` פוסל את הדריסה ו-CI חוסם.

    .. warning::

       **המכל חוסם ``append`` ו-``extend`` בלבד** — אלה שתי המתודות
       שהוא דורס, ותת-מחלקה של ``list`` אינה יכולה לחסום יותר מזה.
       נמדד מול מכל חסום ב-3: חמש דרכי הוספה אחרות עברו ל-9 פריטים
       בשקט — ``rows += [...]``, ``rows[len(rows):] = [...]``,
       ``list.append(rows, x)``, ``rows.insert(0, x)`` ו-
       ``list.extend(rows, ...)``.

       זו הסיבה שיש **גם** טסט שסורק את מקור שלושת הסורקים ומאמת שאין
       בהם אף אחת מחמש הצורות (נמדד היום: אפס). מכל שנראה כמו הגנה
       מלאה ואינו כזה מייצר ביטחון שווא, וזה בדיוק מה שהוא בא למנוע.
    """

    def append(self, item: Any, /) -> None:
        if len(self) >= MAX_SYMBOLS:
            raise TooManySymbols
        super().append(item)

    def extend(self, items: Iterable[Any]) -> None:
        # אחד-אחד ולא ``super().extend``, כדי שהסירוב ייפול **בפריט**
        # שחוצה את התקרה ולא אחרי שכולם נכנסו. זה מה שמשאיר את השיא
        # חסום ולא רק את התשובה.
        for item in items:
            self.append(item)


def too_many_symbols() -> dict[str, Any]:
    """התשובה שהסורק מחזיר כשהתקרה נחצתה.

    ``status`` ולא ``error``: הקריאה עצמה הצליחה, ו-
    ``test_a_scanner_returning_a_shape_outside_the_contract_fails_loudly``
    הופך כל מילת ``status`` שאינה ``ok``/``no_outline`` ל-``TypeError``.

    **ואין כאן ``symbols``, אין ``total``, ואין ``truncated``.** קורא
    שיקרא ``symbols`` בלי לבדוק ``status`` יקבל ``KeyError`` — ולא רשימה
    חלקית שנראית שלמה. מפה חלקית שמתחזה למלאה היא בדיוק הכשל שהמודול
    הזה קיים כדי למנוע, ו-
    ``test_the_response_does_not_carry_a_truncated_flag`` כבר קיבע שאין
    חיתוך בשקט.

    ``max`` ולא ``limit``, כדי לדבר באוצר המילים של ``page_too_large``
    שמחזיר ``max`` באותה משפחה. **ואין ``count``**, כי נעצרנו — איננו
    יודעים כמה סימבולים יש בקובץ, ומספר שנראה כמו סך הוא שקר.
    """
    return {"status": "no_outline", "reason": "too_many_symbols", "max": MAX_SYMBOLS}
