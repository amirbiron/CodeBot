"""סורקי האאוטליין — מודול לכל שפה, וכולם באותו חוזה.

**החבילה הזו ריקה מקוד רץ בכוונה.** ``mcp_server/__init__.py`` מסביר למה:
``import database.schemas`` מריץ את ``database/__init__.py``, ושורה 11 בו היא
``db = DatabaseManager()`` — חיבור למונגו בזמן טעינת מודול. ``__init__`` שמייבא
סורקים כדי "לחסוך שורה" הוא בדיוק אותה מלכודת בקנה מידה קטן: הוא הופך כל ייבוא
של סורק אחד לטעינה של כולם. הייבוא נעשה ב-``mcp_server/outline.py``, במקום אחד
ומפורש.

**ומה שסורק כן מייבא: ספריית תקן, ומודולי אחות פרטיים בחבילה הזו.** הניסוח
הקודם אמר "ספריית תקן בלבד", וזה לא נכון עוד: ``html.py`` מייבא את ``css``
(כדי לסרוק גוף של ``<style>``), ושני הסורקים מייבאים את ``_lines`` ואת
``_ceiling``. **מה שכן אסור הוא ייבוא לרוחב בין שפות** — ``css`` אינו מייבא
מ-``html``, ו-``python`` אינו מייבא מאף סורק — וכל הגיון שמשותף לכמה סורקים
עובר למודול אחות בקו תחתון תחתית, ולא נקרא מסורק שכן. הכיוון הזה נמדד:
ייבוא ``html`` טוען ``css``, ``_lines`` ו-``_ceiling``, ואינו טוען ``python``.

**ולסורק אחד מותר לייבא מחוץ לחבילה, וזו הרחבה מוצהרת של הכלל.** ``rst``
מייבא ``services.rst_parser``. ההיתר אינו "כי היה נוח", והוא נשען על ארבעה
דברים שכל אחד מהם נמדד או מאומת:

1. **הייבוא קל, וזה מה שנמדד בפועל.** ``from services import rst_parser``
   מושך **אפס** מודולים כבדים: לא pymongo, לא bson, לא ``database``, לא
   telegram, לא flask. כלומר המלכודת שבראש הקובץ הזה,
   ``db = DatabaseManager()`` בזמן טעינת מודול, אינה נגישה מכאן. זה
   האינווריאנט שמחזיק את ההיתר הזה. **ומה שנאכף בטסט הוא הענף השני
   בלבד:** ``tests/test_doc_sections.py`` מריץ בתת-תהליך נקי את המדידה
   הזאת על ``services.doc_sections``. הענף של ``rst_parser`` עצמו נמדד
   ידנית ואינו מכוסה בטסט, וזה פער מוצהר ולא הבטחה.

   מהריפו נטענים **שני חלקים, ואחד מהם מותנה**. הקבוע הוא שרשרת
   ה-``services``: החבילה עצמה, ``services.backoff_state`` (כי
   ``services/__init__.py`` מייבא ממנה ``state``), ``services.rst_parser``
   ו-``services.doc_sections``. המותנה הוא זנב ש**תלוי במה שמותקן בסביבה
   ולא בשורת קוד**: ``services/backoff_state.py`` **מנסה** לייבא
   ``observability``, ו-``observability.py`` מייבא ``structlog`` בקשיחות —
   ולכן בסביבה שבה ``structlog`` מותקן נטענים גם ``observability`` וגם
   ``monitoring.error_signatures`` שהוא מנסה לייבא בעצמו, ובסביבה שבה הוא
   חסר לא נטען אף אחד מהם.

   ``services.doc_sections`` הצטרף כשהמודל המשותף חולץ לשם, ו**התוספת נמדדה
   על שני העצים באותה סביבה**: מודול אחד בדיוק, ואפס כבדים — הוא מייבא ``re``,
   ``dataclasses``, ``difflib`` ו-``typing`` בלבד.

   **ולכן אין כאן מספר מקובע, לא של הסך הכול ולא של מודולי הריפו.** אותו
   ייבוא עצמו נמדד 73 מודולים בסביבה בלי ``structlog`` ו-330 בסביבה איתו —
   פי ארבעה וחצי, בלי ששורת קוד אחת השתנתה. גם רשימה סגורה של שמות מתיישנת
   מאותה סיבה בדיוק, וזה כבר קרה כאן: הניסוח הקודם מנה ארבעה מודולים
   מהריפו והחמיץ את שלושת המותנים. מה שמחזיק הוא האינווריאנט למעלה —
   **אפס מודולים כבדים** — והוא נמדד בשתי הסביבות.

   **ו-``services/__init__.py`` אינו רק הצהרות, בניגוד למה שנכתב כאן
   קודם.** הוא מייבא ``from .backoff_state import state``, ולכן
   ``services/backoff_state.py`` מריץ בזמן הטעינה ``threading.RLock()``
   ובנייה של אובייקט מצב, ומנסה לייבא ``observability``. שלושתם קלים
   וכולם עטופים ב-``try``, ולכן המסקנה עומדת — אבל היא עומדת על המדידה
   הזאת ולא על "18 שורות בלי קוד".
2. **יש תקדים מודולי בדיוק לזה.** ``mcp_server/docs_handlers.py`` מייבא
   ``from services import rst_parser`` ברמת המודול, וזה הייבוא הלא-עצל
   היחיד מ-``services`` תחת ``mcp_server``.
3. **וזה אינו ייבוא לרוחב בין סורקים** — מה שהכלל למעלה אוסר.
   ``rst_parser`` אינו סורק ואינו בחבילה הזו; הוא מודול שנבנה מראש כדי
   לשמש כמה כלים, וכתוב כך ב-docstring שלו.
4. **והחלופה נמדדה ונדחתה.** יישור זיהוי הכותרות של ``rst_parser``
   לפארסר של docutils דרש סגירת תשע סטיות מול שתי טבלאות אמת. פארסר שני
   בחבילה הזו, שיצטרך להסכים עם הראשון לנצח, הוא בדיוק החוב שההיגיון
   הזה יקר מדי בשבילו.

**ומה שההיתר הזה אינו:** רשות לייבא מ-``services`` בכלל. כל מודול נוסף שם
נשקל מחדש מול ארבעת הסעיפים — ובראשם המדידה, לא ההנחה.

**החוזה, זהה לכל הסורקים:**

``extract(text: str) -> dict``

מחזיר ``{"symbols": [{"name": str, "start": int, "end": int}, ...]}`` בהצלחה,
או ``{"status": "no_outline", "reason": ..., ...}`` בכשל. ``start``/``end``
הן 1-indexed וכוללות את שני הקצוות, כדי שאפשר יהיה להעביר אותן ישירות
ל-``lines=[start, end]``.

**ולסורק אחד יש נקודת כניסה שנייה, מוצהרת:** ``css.read_blocks`` נקראת
מ-``html.py`` כדי לסרוק גוף של ``<style>``. היא **אינה** ``extract``: היא
מקבלת גבולות, תחילית, ואת רשימת השורות של הקורא, וכותבת לתוכה. סורק שמשמש
כתת-סורק חייב את הצורה הזאת — התקציב של התקרה הוא לכל הקובץ, לא לכל בלוק —
ולכן היא ציבורית בכוונה ולא בטעות.

הסורק **אינו** ממיין ו**אינו** מסנן לפי ``symbol`` — שני אלה יושבים במנתב.
סורק שמשכפל אותם הוא סורק שאפשר לשכוח בו אחד מהם, והתוצאה תהיה עימוד לא
יציב בשפה אחת בלבד — כשל שקט שיתגלה רק כשמישהו יבקש עמוד שני.
"""
