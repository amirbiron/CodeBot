"""סורק האאוטליין של RST — הכותרות כתוכן עניינים, והתוויות כיעדים.

**הסימבול הוא כותרת, והמפה היא תוכן עניינים עם טווחי שורות.** קובץ תיעוד
הוא בדיוק המקום שבו חיפוש טקסט מאכזב: השאילתה ``רמת לוג`` תמצא עשרים
אזכורים בפרוזה ולא את הסעיף שמגדיר אותה. מפה שאומרת שהסעיף יושב בשורות
410-470 שווה יותר, כי אחריה אפשר להמשיך ישר ל-``lines=[410, 470]``.

**ובנוסף — יעדי ``.. _label:``.** אלה היעדים שאליהם ``:ref:`` מצביע, וכשקישור
בתיעוד נשבר זה בדיוק מה שמחפשים: לא "איפה כתוב על X" אלא "איפה מוגדר
העוגן שאליו ההפניה השבורה הזאת מכוונת".

**הסורק הזה דק בכוונה, והוא לא מפרסר.** ההיררכיה של כותרות RST נקבעת לפי
**סדר הופעת תווי הפיסוק בכל קובץ בנפרד** — ``===`` אינו "רמה 1" — וזה
היגיון שכבר מומש ב-``services.rst_parser``, שיושר לפארסר של docutils 0.23.
כאן רק ממפים את העץ שהוא מחזיר אל חוזה האאוטליין.

**ולמה הוא מייבא מ-``services`` בזמן שאף סורק אחר לא.** ה-docstring של
``outline_scanners/__init__.py`` נושא את הנימוק המלא ואת המדידה; בקצרה:
הייבוא טוען ספריית תקן בלבד, יש תקדים מודולי ב-``mcp_server/docs_handlers.py``,
וההיגיון הזה כבר נמדד כיקר מדי לשכפול — יישורו ל-docutils דרש סגירת תשע
סטיות מול שתי טבלאות אמת.

**השמות מנוקדים לפי ההיררכיה**, מה-``breadcrumb`` שכבר מחושב:
``התקנה.דרישות.פייתון``. אותה החלטה שנקבעה לפייתון, ולכן היא עקבית ולא
חדשה — ו-``symbol=`` מסנן על השם המלא.

**וכן, כותרת המסמך הופכת לתחילית של כל שם, וזה מכוון.** ברוב קובצי ה-RST
יש כותרת רמה 1 אחת שהכול מקונן תחתיה, ולכן היא חוזרת בכל שורה במפה. זה
נראה כמו רעש שכדאי לקצץ, ואין לקצץ אותו: **התחילית היא מה שמפריד שתי
כותרות זהות תחת אבות שונים** — ``מטרה`` תחת ``Alpha`` מול ``מטרה`` תחת
``Beta`` — וזו בדיוק ההבחנה שהמפה קיימת בשבילה. וקובץ עם כמה כותרות רמה 1
אינו היפותטי, ושם התחילית אינה קבועה כלל. המחיר נמדד ואינו לוחץ: העמוד
הגדול בקורפוס הוא 4,760 בתים מול תקציב של 256,000. ו-``symbol=`` מסנן
בהכלה, ולכן ``symbol="מה זה נותן"`` עובד בלי לדעת את התחילית.

**והנקודה בשם אינה מפריד בלעדי — זה נמדד, וזו התנהגות מוצהרת.** בקורפוס
הזה **90 מתוך 1,337 הכותרות מכילות נקודה בעצמן**, ב-55 קבצים, וכמעט כולן
עמודי autodoc עם כותרות כמו ``chatops.permissions module``. כלומר
``a.b.c`` יכול להיות "``c`` תחת ``a.b``" או "``b.c`` תחת ``a``", ואי אפשר
להכריע מהשם לבדו. **השם הוא תווית ל-``symbol=`` ואינו מבנה שנפרס חזרה**,
וההשתייכות נקראת מטווח השורות — בדיוק הנימוק שבגללו ``style#theme..foo``
אפשרי בסורק ה-HTML. קוד שמפרק את השם בנקודה כדי למצוא אב יטעה על 6.7%
מהקורפוס, וזה כבר קרה בגרסה ראשונה של אחד הטסטים כאן.

**וטקסט הכותרת נשאר גולמי ואינו מנורמל** — ``:ref:`` ו-``docs_get_section``
רואים ``code`` שם ש-docutils מרנדר, ואנחנו מחזירים `` ``code`` `` כפי שכתוב
בקובץ. זו הכרעה ולא השמטה: ``start`` מצביע לשורה **בקובץ המקור**, ושם
מנורמל לא היה תואם לשורה שאליה הוא מצביע — ואז המפה מפסיקה להיות מפה של
הקובץ. וגם אורקל השורה בטסטים, שמאמת ש-``start`` נושא את הכותרת שדווחה,
היה נאלץ לנרמל בעצמו — ואז שני צידי ההשוואה יוצאים ממקור אחד.

**שתי החלטות שנכתבות מראש כדי שלא ייראו כבאג:**

- **קובץ בלי אף כותרת אינו כשל.** הוא מחזיר רשימה ריקה, כמו קובץ CSS בלי
  כללים. ``no_outline`` שמור לסיומת שאין לה סורק ולתקרה. (בקורפוס הזה אין
  אף קובץ כזה, אבל הכלי משרת כל ריפו ממורר.)
- **``symbol="_"`` מחזיר את התוויות**, כי הסינון במנתב הוא בהכלה והתוויות
  הן השמות היחידים שמתחילים בקו תחתון. זו הבטחה שכתובה בתיאור הכלי, ולכן
  יש לה טסט.

.. note::

   **מה שזה עולה על קובץ גדול, נמדד — והתקרה נוסעת פנימה בגלל המדידה.**
   ``parse_document`` בנה את כל הסקשנים לפני שהתקרה כאן נגעה בהם, ולכן
   הוא מקבל עכשיו ``max_sections`` ועוצר בזמן הפרסור. נמדד על 10MB של
   כותרת בת תו אחד בכל שתי שורות — 2.6 מיליון סקשנים: **18.5 שניות
   ו-1,132MB** בלי התקרה, מול **0.30 שניות ו-83MB** איתה. הזיכרון הוא
   הנתון שמצדיק את זה: בקשה איטית היא בקשה איטית, אבל ג'יגה-בייט בתהליך
   משותף מפיל שירות.

   **ומה שנשאר פתוח, במפורש.** התקרה מגבילה סקשנים ולא שורות, ולכן קלט
   שאינו מייצר סקשנים כלל אינו נחסם: 10MB של שורות ריקות הוא **אפס
   סקשנים ו-6.3 שניות**, זהה עם התקרה ובלעדיה. שם החסם היחיד היום הוא
   ``RANGE_READ_MAX_BYTES``. השארית הזאת עולה זיכרון וזמן בתהליך משותף,
   וזה נשאר נכון — אבל **היא כבר אינה נועלת את לולאת האירועים.** גופי
   הכלים עברו לחוטי עובד ב-#3379, שנסגר; מה שהשארית תופסת היום הוא חוט
   מתוך מספר חסום, לא את הלולאה. הטיפול בה עדיין אינו כאן: תקרה על
   שורות, להבדיל מתקרה על סקשנים, היא שינוי משלה.
"""

from __future__ import annotations

import re
from typing import Any

from services import rst_parser

from . import _ceiling

#: יעד פנימי מפורש — השם שאליו ``:ref:`` מצביע.
#:
#: התחביר מאומת מ-``explicit.patterns.target`` שב-docutils 0.23: אחרי סמן
#: ה-explicit markup בא ``_``, ואז שם שאינו מתחיל ב-``_`` (זהו יעד
#: **אנונימי**, שאין לו שם ואי אפשר להפנות אליו ב-``:ref:``) ואינו מתחיל
#: ברווח, ואז נקודתיים. הצורה עם ה-backquotes קיימת במקור כדי לאפשר
#: נקודתיים **בתוך** השם, ולכן היא חלופה ולא הרחבה.
#:
#: **והדרישה שהשורה תיגמר בנקודתיים אינה קוסמטית.** ``.. _site: http://x``
#: הוא יעד **חיצוני** — נמדד ב-docutils שהוא מקבל ``refuri`` — ו-``:ref:``
#: אינו יכול להצביע אליו. בלי העיגון לסוף השורה הוא היה נכנס למפה כיעד
#: פנימי. בקורפוס הזה יש אפס יעדים חיצוניים, כלומר זו הגנה על ריפו אחר.
#:
#: **ו-``^`` מחייב column 0**, וזה נמדד ולא הונח: היעד היחיד המוזח בקורפוס
#: יושב ב-``docs/versioning-stable-anchors.rst`` בתוך ``.. code-block:: rst``,
#: כלומר הוא דוגמה בתוך בלוק ליטרלי ולא יעד. שורה מוזחת אינה explicit markup.
_LABEL = re.compile(
    r"^\.\.[ \t]+_"
    r"(?:`(?P<quoted>[^`]+)`|(?!_)(?![ `])(?P<name>(?:[^:\\]|\\.)+))"
    r":[ \t]*$"
)


def extract(text: str) -> dict[str, Any]:
    """מפת הסימבולים של קובץ RST.

    זהו חוזה הסורק שהמנתב קורא לו.

    **ערוץ הכשל היחיד הוא התקרה**, וזה מתועד כאן במפורש לפי ``K11``:
    ``parse_document`` סלחני במכוון ואינו זורק על קלט פגום — כותרת בלי קו,
    קו בלי כותרת, בלוק שלא נסגר — והוא מחזיר את מה שכן זיהה. זה נמדד על כל
    קובצי ה-RST בריפו ועל שתי טבלאות צורות. לכן אין כאן ``except`` רחב:
    באג שלנו חייב ליפול בקול ולא להתחפש ל"אין אאוטליין" על קובץ תקין.
    (``TypeError`` על ``text`` שאינו מחרוזת, מאז #3421, הוא בדיוק כזה:
    ``text`` כאן תמיד מחרוזת מפוענחת, ולכן זה חוזה שנשבר ולא קלט פגום.)

    **והתקרה מועברת כאן במפורש — ``_ceiling.MAX_SYMBOLS`` — ולא נשענת על
    ברירת המחדל של הפארסר**, גם אחרי ש-#3420 יישר אותה לאותו מספר: המספר
    כאן הוא של המפה (כותרות ותוויות יחד, ``Capped``), והסורק אומר אותו
    בעצמו. טסט מקבע שהקריאה נושאת אותו.

    התקרה נוסעת פנימה כחריגה ויוצאת כאן כערך החזרה — הנימוק ב-
    ``_ceiling.TooManySymbols`` — וה-``except`` תופס **את שתי החריגות
    בשמן, ולא רחב מזה**.

    **ושתיים ולא אחת, כי יש שני מקומות שבהם אותה תקרה נחצית.**
    ``TooManySections`` מורמת בתוך ``parse_document`` כשהכותרות לבדן
    ממלאות אותה, ו-``TooManySymbols`` מורמת מהמכל כאן כשהכותרות והתוויות
    **יחד** חוצות אותה. אותו מספר, אותה תשובה, ושני שערים כי העבודה
    מתחלקת בין שני מודולים.

    **והפרסור יושב בתוך ה-``try`` ולא לפניו** — אחרת החריגה שנוסעת
    פנימה עולה בלי מי שיתפוס אותה, והתשובה על קובץ פתולוגי הופכת
    מ-``no_outline`` לשגיאת כלי.
    """
    rows: list[dict[str, Any]] = _ceiling.Capped()
    try:
        document = rst_parser.parse_document(text, max_sections=_ceiling.MAX_SYMBOLS)
        for section in document.sections:
            rows.append(
                {
                    # ``heading_line`` ולא ``title_line``: בכותרת עם overline
                    # שורת הטקסט היא השנייה מהשלוש, והטווח צריך להתחיל בקו
                    # שמעליה — אחרת ``lines=`` שיבוא אחרי המפה יחתוך אותו.
                    "name": ".".join(section.breadcrumb),
                    "start": section.heading_line,
                    "end": section.end_line,
                }
            )
        for number, line in enumerate(document.lines, 1):
            found = _LABEL.match(line)
            if found is None:
                continue
            # **בלוק ה-explicit markup נמשך על שורות מוזחות, ושם הוא הופך
            # את התווית לחיצונית.** ``parse_target`` שב-docutils מחזיר
            # ``'refuri'`` על **כל** תוכן בבלוק — בלי שום אימות שזה URI —
            # ולכן ``.. _site:`` ואחריו שורה מוזחת הוא יעד חיצוני ש-``:ref:``
            # אינו יכול להצביע אליו, גם כשהשורה המוזחת היא פרוזה רגילה.
            #
            # וזו הסיבה שהבדיקה היא "מוזחת ולא ריקה" ולא "נראית כמו URI":
            # הצורה השנייה הייתה מפספסת את אותו יעד בדיוק. נמדד מול
            # docutils על URI בשורה אחת, על URI שנשבר לשתיים, על הזחת טאב
            # ועל פרוזה — כל הארבע חיצוניות. ובכיוון השני, שורה **ריקה**
            # בין השתיים מסיימת את הבלוק, ואז התווית פנימית.
            #
            # הצורה שבה ה-URI באותה שורה (``.. _site: http://x``) נחסמת
            # ממילא בעיגון לסוף השורה שב-``_LABEL``.
            following = document.lines[number] if number < len(document.lines) else ""
            if following.strip() and following[:1] in (" ", "\t"):
                continue
            # השם נשמר עם הקו התחתון כפי שהתווית נכתבת בקובץ, ולא בלעדיו.
            # שתי סיבות: כך הוא נראה בקובץ ולכן ``symbol=`` עליו טבעי, והוא
            # אינו יכול להתנגש בכותרת שנושאת את אותו שם בדיוק.
            rows.append(
                {
                    "name": "_" + (found.group("quoted") or found.group("name")),
                    # יעד הוא נקודה ולא טווח, ולכן שני הקצוות שווים. זה גם מה
                    # שמבדיל אותו במפה מכותרת, בלי להוסיף שדה לחוזה.
                    "start": number,
                    "end": number,
                }
            )
    except (rst_parser.TooManySections, _ceiling.TooManySymbols):
        return _ceiling.too_many_symbols()
    return {"symbols": rows}
