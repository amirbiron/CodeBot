"""גיל התיאור — מקור אמת יחיד לכלל שאחרת היה מפוזר בשישה אתרי כתיבה.

ב-Ck כל "גרסה" של קובץ היא מסמך חדש באוסף, וה-``description`` מועתק
מהגרסה הקודמת לחדשה. זו ברירת מחדל נכונה — עריכת שורת קוד אינה מבטלת את
התיאור — אבל התוצאה שלה היא שתיאור שנכתב בגרסה 1 נראה בגרסה 11 בדיוק כמו
תיאור שנכתב אתמול. המודול הזה נותן לו **חותמת**: מספר הגרסה שבה התיאור
נקבע או השתנה לאחרונה, ומתוכה את **הגיל** — כמה גרסאות עברו מאז.

שני חצאי הכלל יושבים כאן יחד בכוונה. :func:`description_stamp_for_new_version`
היא צד הכתיבה ו-:func:`description_age_versions` הוא צד הקריאה; פיצול
שלהם לשני מודולים היה מאפשר לשניים לסטות, וסטייה כזאת לא הייתה מתגלה
בשגיאה אלא במספר שנראה סביר.

המודול טהור בכוונה — ``typing`` ותו לא, בלי Flask, בלי מסד ובלי
``bson``. זה מה שמאפשר גם ל-``database/repository``, גם ל-``webapp/app``
וגם ל-``mcp_server/backend`` לייבא אותו ישירות ברמת המודול, בלי
``try/except`` ובלי עותק fallback. אותה תבנית שכבר עובדת עם
``file_dates``, ``file_deletion`` ו-``user_roles`` — ובוובאפ היא לא
נוחות אלא תנאי: ייבוא מ-``database.repository`` ברמת המודול מפיל את
``import webapp.app`` בסביבה בלי ``MONGODB_URL``, ויש טסט שאוכף את זה.
"""
from __future__ import annotations

from typing import Any

#: שם השדה המאוחסן שנושא את מספר הגרסה שבה התיאור נקבע לאחרונה.
#:
#: מוגדר פעם אחת כי הוא נכתב בשישה מסלולי יצירת גרסה ובמסלול עדכון אחד,
#: ונקרא בשלושה מסלולי קריאה — מחרוזת מודפסת בכל אחד מהם הייתה עשרה
#: מקומות שאפשר לשגות בהם בלי ששום בדיקת טיפוסים תיפול. אותו נימוק בדיוק
#: כמו ``VERSION_CREATED_AT_FIELD`` ב-``file_dates``.
DESCRIPTION_SET_AT_VERSION_FIELD = "description_set_at_version"

#: שם השדה ה**מחושב** שמוחזר ללקוחות ה-MCP. אינו נשמר באף מסמך.
DESCRIPTION_AGE_FIELD = "description_age_versions"


def description_stamp_for_new_version(
    previous: Any,
    description: Any,
    new_version: Any,
) -> int | None:
    """החותמת ל**גרסה חדשה** שנכתבת עכשיו: באיזו גרסה התיאור הזה נקבע.

    **הכלל יושב כאן ולא בכל כותב בנפרד, וזה כל העניין.** כתיבת גרסה חדשה
    של קובץ מתרחשת בשישה מקומות: ``Repository.save_code_snippet`` (הבוט,
    כל כלי הכתיבה של ה-MCP, הפסאדות, שחזור מגיבוי) וחמישה ``insert_one``
    נפרדים ב-``webapp/app.py`` — עריכה, העלאה, שחזור גרסה, שמירת מדריך
    משותף וייצוא Incident Story. ``description`` **כבר** מועתק מהגרסה
    הקודמת בכל ששת המקומות, כל אחד בנוסח משלו; חותמת שהייתה מועתקת באותה
    צורה הייתה נשמטת במקום הראשון שמישהו יוסיף, והשדה היה מדווח "עדכני"
    על תיאור בן אחת-עשרה גרסאות — כלומר בדיוק הכשל שהוא בא לחשוף.
    ``description`` והחותמת שלו הם שני שדות מקושרים שחייבים לזוז יחד
    (``bugbot-rules/linked-field-atomicity.md``).

    **הפונקציה טהורה ואינה כותבת כלום.** היא מחזירה מספר, והכותב מחליט
    איפה להניח אותו. זה מה שמאפשר לשני החיבורים למונגו שבפרויקט —
    ה-``DatabaseManager`` הגלובלי וזה שהוובאפ פותח בעצמו
    (``webapp.app.get_db``) — להזין את אותה לוגיקה.

    **הכללים:**

    - תיאור ריק או שאינו מחרוזת ← ``None``. קובץ בלי תיאור אינו מקבל
      חותמת, ובהתאם גם לא יקבל גיל.
    - אין גרסה קודמת ← הגרסה החדשה. התיאור נקבע עכשיו.
    - התיאור זהה לקודם ← החותמת של הקודם **עוברת כמות שהיא**. זה הענף
      היחיד שמונע איפוס של הגיל בכל עריכה.
    - התיאור שונה ← הגרסה החדשה.
    - גרסה קודמת בלי חותמת תקינה (קובץ מלפני השדה, או כזה שהמיגרציה לא
      הצליחה לחשב) ← ``None``. עריכה אינה יודעת מתי התיאור נכתב, ושתיקה
      עדיפה על מספר שנשמע כמו ידיעה.

    **``None`` פירושו "אל תכתוב את השדה"** ולא "כתוב ``None``": שדה חסר
    הוא מה ש-:func:`description_age_versions` מתרגם ל-``null``, ושדה
    שנושא ``None`` היה מגיע לאותו מקום בדרך ארוכה יותר.

    **``previous`` חסר נחשב "קובץ חדש" ולא "לא ידוע", וזו החלטה.** הוא
    חסר גם כששמירה נוחתת על שם שכל גרסאותיו בסל המיחזור — ושם התיאור
    באמת נקבע עכשיו, ואפס הוא התשובה הנכונה. הוא יכול להיות חסר גם
    כשקריאת הגרסה הקודמת נכשלה, וזה כבר ניחוש; אבל באותו מסלול בדיוק גם
    ``created_at`` וסימון הנעיצה כבר נלקחים כאילו אין קודם
    (``save_code_snippet``), ומספור הגרסה עצמו מפיל את השמירה כשהוא לא
    מצליח לברר. הפרדה בין שני המצבים אינה זמינה בשכבה הזו.

    ``isinstance`` ולא ``str(...)``: ``description`` מגיע מגוף JSON של
    כלי MCP או משדה טופס, כלומר מחוץ לתהליך, והמרה שקטה של ``42``
    למחרוזת ``"42"`` הייתה קוברת קלט פגום במקום לדחות אותו
    (``bugbot-rules/external-input-isinstance.md``).
    """
    if not isinstance(description, str) or not description:
        return None
    version = _as_version(new_version)
    if version is None:
        return None
    if not isinstance(previous, dict):
        return version
    previous_description = previous.get("description")
    if not isinstance(previous_description, str):
        previous_description = ""
    if previous_description != description:
        return version
    previous_stamp = _as_version(previous.get(DESCRIPTION_SET_AT_VERSION_FIELD))
    if previous_stamp is None or previous_stamp > version:
        # חותמת גבוהה ממספר הגרסה אינה מצב שהקוד הזה מייצר, ולכן היא נתון
        # פגום ולא ידיעה. גיל שלילי היה נקרא כמו תיאור מהעתיד.
        return None
    return previous_stamp


def description_age_versions(doc: Any) -> int | None:
    """כמה גרסאות עברו מאז שהתיאור נקבע — או ``None`` כשלא ידוע.

    **מחושב בזמן קריאה ואינו נשמר.** ערך שמור היה חייב להתעדכן בכל
    שמירה, והשמירה שתשכח אותו הייתה מייצרת בדיוק את השקר שהשדה בא
    לחשוף. חיסור של שני מספרים אינו שווה את הסיכון הזה.

    **``None`` ולעולם לא ``0`` כשלא ידוע.** אפס הוא טענה — "התיאור נכתב
    לגרסה הזו" — ומי שאין לו חותמת אינו יודע אותה. שלושת המסלולים
    שמחזירים ``None``: מסמך בלי מספר גרסה (קובץ גדול ב-``large_files``
    אינו ממוספר כלל), מסמך בלי חותמת (נכתב לפני השדה, או שהמיגרציה לא
    הצליחה לשחזר), וחותמת שגבוהה ממספר הגרסה.

    מחזירה ``None`` גם לקובץ **בלי תיאור** — ושם הקורא אמור לא להחזיר את
    השדה בכלל, כי אין תיאור שאפשר לבדוק את גילו. ההבחנה בין שני סוגי
    ה-``None`` שייכת לקורא ולא לכאן: כאן יש רק שאלה אחת, "מה הגיל",
    ולשתיהן אין לה תשובה.

    **הגיל הוא הפרש של מספרי גרסה, לא מניין עריכות שקרו.** מספור הגרסאות
    רץ על כל המסמכים של אותו שם קובץ כולל אלה שבסל המיחזור
    (``_max_version_any_state``), ולכן גרסאות שנמחקו משאירות חורים ברצף
    והגיל יוצא גדול במקצת ממספר העריכות בפועל. זה לא משנה את מה שהשדה
    משמש לו — סדר גודל, לא ספירה מדויקת.
    """
    if not isinstance(doc, dict):
        return None
    version = _as_version(doc.get("version"))
    if version is None:
        return None
    stamp = _as_version(doc.get(DESCRIPTION_SET_AT_VERSION_FIELD))
    if stamp is None or stamp > version:
        return None
    return version - stamp


def description_age_field(doc: Any) -> dict:
    """מה שמסלולי הקריאה מוסיפים לתשובה — ``{}`` או ``{השדה: גיל-או-None}``.

    **ההחלטה אם השדה מופיע בכלל שייכת לכאן ולא לכל קורא בנפרד**, כי היא
    ההבחנה שהכי קל לטעות בה: ``null`` ו"אין שדה" אינם אותו דבר. ``null``
    אומר *"יש כאן תיאור ואיני יודע בן כמה הוא — לך תבדוק"*, ולכן הוא
    קריאה לפעולה; היעדר השדה אומר *"אין כאן מה לבדוק"*, ולכן הוא שקט.
    לשפוך את שניהם ל-``null`` היה מייצר התראה על כל קובץ בלי תיאור.

    שני מקרים מחזירים ``{}``:

    - **קובץ בלי תיאור.** אין טקסט שאפשר לשאול על גילו.
    - **מסמך בלי מספר גרסה.** קובץ גדול (``large_files``) נשמר בדריסה
      ולא בגרסאות ואין לו ``version`` כלל — "גיל בגרסאות" אינו מושג
      שקיים שם, ו-``null`` היה שולח את הסוכן לבדוק משהו שאין בו מה
      לבדוק.

    ``null`` נשאר למקרה שהוא באמת מתאר: קובץ **ממוספר** שיש לו תיאור
    ואין לו חותמת — נכתב לפני שהשדה קיים, או שהמיגרציה לא הצליחה
    לשחזר את שרשרת הגרסאות שלו.
    """
    if not isinstance(doc, dict):
        return {}
    description = doc.get("description")
    if not isinstance(description, str) or not description:
        return {}
    if _as_version(doc.get("version")) is None:
        return {}
    return {DESCRIPTION_AGE_FIELD: description_age_versions(doc)}


def _as_version(value: Any) -> int | None:
    """מספר גרסה חיובי, או ``None`` לכל דבר אחר.

    ``bool`` נפסל מפורשות: הוא תת-מחלקה של ``int`` בפייתון, ו-``True``
    היה עובר כ-1 ונקרא כ"התיאור נקבע בגרסה הראשונה".

    ``int(value)`` על מחרוזת נעשה בכוונה ולא נדחה — מסמכים ישנים במונגו
    נושאים לעיתים מספרים כמחרוזות, וזה אותו ``int(...)`` שכבר מריצים
    ``_max_version_any_state`` והראוטים בוובאפ על אותו שדה בדיוק.
    """
    if isinstance(value, bool) or value is None:
        return None
    try:
        number = int(value)
    except (TypeError, ValueError):
        return None
    return number if number >= 1 else None
