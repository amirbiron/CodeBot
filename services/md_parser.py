class _SectionCounter:
    """סופר **כותרות** תוך כדי הפרסור, בלי לסרוק טוקן פעמיים.

    **כל** ``heading_open``, גם כזה שיושב בתוך ציטוט או בתוך פריט
    רשימה ולכן לא ייכנס למפה. זה מכוון: התקרה מגבילה **עבודה** ולא
    **תוצאה**, ומה שמייקר את הפרסור הוא הכותרת עצמה — לא השאלה אם
    היא נספרת כסעיף בסוף. נמדד: 500KB של ``> ## h`` הם ~64,000
    כותרות שאף אחת מהן אינה סעיף, וספירה לפי ``level == 0`` הייתה
    רואה בהן אפס ולא עוצרת לעולם.

    **המצב יושב כאן ולא על המופע המשותף של ``MarkdownIt``.** המופע נבנה
    פעם אחת ברמת המודול ונקרא ממספר חוטים — גופי הכלים רצים ב-
    ``asyncio.to_thread`` — ולכן מונה שהיה יושב עליו היה מרוץ. ``env``
    הוא פר-פרסור ומועבר לתוך ``md.parse``, ואומת שהוא אותו אובייקט
    שיוצא בסוף.

    **ו-``scanned`` הוא כל העניין.** כלל שסורק את ``state.tokens`` כולו
    בכל קריאה הוא O(n²), וזה בדיוק מה שהופך תקרה שנועדה לחסוך עבודה
    למקור העבודה. ``examined`` נספר כדי שאפשר יהיה לטעון על זה בטסט
    במקום למדוד זמן שמתנדנד ב-CI.
    """

    __slots__ = ("max_sections", "seen", "scanned", "examined")

    def __init__(self, max_sections: int) -> None:
        self.max_sections = max_sections
        self.seen = 0
        self.scanned = 0
        self.examined = 0

    def scan(self, tokens: List[Token]) -> bool:
        """סורק את הטוקנים החדשים בלבד. ``True`` = התקרה נחצתה.

        **צורת** הגבול זהה ל-``Capped.append`` וְל-``add_section`` ב-
        ``rst_parser`` — קלט עם בדיוק ``max_sections`` יחידות עובר
        במלואו, והיחידה שמעליו עוצרת — אבל **היחידה עצמה שונה**: שם
        סקשן, כאן כותרת, כולל כותרת בתוך מכל שלא תיכנס למפה. ראו את
        ה-docstring של המחלקה.
        """
        for token in tokens[self.scanned:]:
            self.examined += 1
            if token.type == "heading_open":
                self.seen += 1
        self.scanned = len(tokens)
        return self.seen > self.max_sections


def _ceiling_rule(state, startLine: int, endLine: int, silent: bool) -> bool:
    """כלל בלוק שאינו מייצר טוקנים — הוא רק סופר, ועוצר בתקרה.

    החתימה היא ``RuleFuncBlockType`` של ``markdown_it/parser_block.py``,
    ו-``False`` פירושו "לא אני" — כלומר שרשרת הכללים ממשיכה כרגיל
    והפלט זהה בדיוק לפלט בלי הכלל הזה.

    **למה בתוך הפרסור ולא אחריו:** ``ParserBlock.tokenize`` קורא לכל
    כלל בתחילת כל בלוק, כולל בתוך ציטוטים ורשימות (הוא משתמש ב-
    ``getRules("")``, שהיא **כל** הכללים). לכן חריגה כאן עוצרת את העבודה
    באמצע. נמדד על 50 כותרות עם תקרה של 5: העצירה בשורה 23 מתוך 201.
    בדיקה אחרי ``md.parse`` הייתה מסננת פלט אחרי שכל העבודה כבר נעשתה —
    וזה בדיוק ההבדל שנמדד ב-``_ceiling.py``.
    """
    counter: Optional[_SectionCounter] = state.env.get(_ENV_COUNTER)
    if counter is not None and counter.scan(state.tokens):
        raise TooManySections(startLine + 1)
    return False


#: המפתח שתחתיו יושבת רשימת הטוקנים עם התקרה ב-``env`` של פרסור בודד.
#: :func:`parse_document` בונה אותה, :func:`_install_token_ceiling` מתקין אותה,
#: ו-:func:`parse_document` בודק אחרי הפרסור שזו הרשימה שחזרה.
_ENV_TOKENS = "ck_md_capped_tokens"


class _CappedTokens(List[Token]):
    """רשימת הטוקנים של פרסור אחד, עם תקרה שנבדקת בכל הוספה.

    **למה ברשימה עצמה.** כל טוקן בלוק ש-``markdown-it-py`` יוצר נוצר ב-
    ``StateBlock.push``, שהשורה האחרונה שלו היא ``self.tokens.append(token)``
    (``rules_block/state_block.py``). ‏``self.tokens`` היא הרשימה שכלל ה-core
    ``block`` מעביר (``rules_core/block.py``), ו-``MarkdownIt.parse`` מחזיר אותה.
    כלומר ``append`` כאן הוא הנקודה היחידה שכל טוקן עובר בה — גם בתוך טבלה
    ורשימה, שנבנות בקריאה אחת לכלל. אומת בהרצה: רשימה-מרגלת על 279 מסמכים
    ו-472,932 טוקנים ראתה רק ``append``, ואף פעם לא ``extend``, ``insert`` או
    השמה (markdown-it-py 4.2.0, 2026-09-27).

    **והחריגה אינה נבלעת בדרך החוצה.** ה-``try`` היחידים במסלול הם ``except
    IndexError`` צרים סביב קריאת תו, ו-``except AttributeError`` אחד שעוטף רק
    את ``is_code_block`` (``mdit_py_plugins/utils.py``). חריגה שנזרקת כאן עולה עד
    :func:`parse_document`, ומה שנבנה עד אז נזרק איתה.

    **המחיר:** ``append`` בפייתון במקום ב-C, לכל טוקן. על הקובץ השמור הצפוף
    ביותר (38,153 טוקנים) לא נמדד הבדל — 0.16 שניות עם התקרה ובלעדיה.
    """

    __slots__ = ("limit",)

    def __init__(self, limit: int) -> None:
        super().__init__()
        self.limit = limit

    def append(self, token: Token) -> None:
        # ``>=``: הטוקן שהיה נכנס במקום ה-``limit + 1`` הוא החורג, ולכן קלט של
        # בדיוק ``limit`` טוקנים עובר במלואו — אותה צורת גבול כמו
        # ``_SectionCounter.scan``.
        if len(self) >= self.limit:
            raise TooManyTokens(self._last_line(), self.limit)
        super().append(token)

    def _last_line(self) -> Optional[int]:
        """השורה (1-מבוססת) של הטוקן האחרון שיש לו ``map`` — כלומר היכן הפרסור היה.

        הטוקן החורג עצמו עוד בלי ``map``: הכללים מציבים אותו **אחרי** ש-``push``
        חוזר (למשל ``token.map = [nextLine, nextLine + 1]`` ב-``table.py``), ולכן
        הולכים אחורה. טוקני סגירה ו-``td_open`` אינם נושאים ``map``, כך שההליכה
        קצרה, והיא רצה פעם אחת — ברגע הסירוב. ``None`` כשאין עדיין טוקן עם
        מיקום, ואז הסירוב אינו נושא ``line`` בכלל.
        """
        for token in reversed(self):
            if token.map is not None:
                return token.map[0] + 1
        return None


def _install_token_ceiling(state: StateCore) -> None:
    """כלל core שרץ לפני ``block``: מתקין את רשימת הטוקנים עם התקרה, כשיש כזו.

    **למה כלל ולא ארגומנט לבנאי.** ``StateCore.__init__`` עושה ``self.tokens =
    tokens or []`` (``rules_core/state_core.py``), ולכן רשימה שמועברת **ריקה**
    — ורשימה חדשה תמיד ריקה — נבלעת בשקט ומוחלפת ברשימה רגילה: פרסור בלי תקרה
    שנראה בדיוק כמו פרסור עם תקרה. הכלל רץ אחרי ``normalize`` ולפני ``block``,
    כלומר לפני שנוצר טוקן אחד. והמעקה ב-:func:`parse_document` בודק אחרי הפרסור
    שזו אכן הרשימה שחזרה, כך שהחלפה עתידית כלשהי נכשלת בקול.

    **המצב של כל פרסור יושב ב-``env`` ולא על המופע המשותף** (U1), בדיוק כמו
    מונה הכותרות: :func:`parse_document` בונה את הרשימה, והכלל רק מתקין אותה.
    כשאין רשימה ב-``env`` — פרסור החימום, ``token_count``, ``front_matter_end``
    — הכלל אינו עושה דבר.
    """
    capped: Optional[_CappedTokens] = state.env.get(_ENV_TOKENS)
    if capped is None:
        return
    if state.tokens:
        # אין מסלול כזה היום: ``normalize`` הוא הכלל היחיד לפני ``block``, והוא
        # נוגע רק ב-``src``. הרמה כאן פירושה שהספרייה שינתה חוזה — אותה הכרעה
        # כמו ``heading_open`` בלי ``map`` ב-``_sections_from_tokens``.
        raise RuntimeError(
            "markdown-it יצר טוקנים לפני הכלל ck_max_tokens — "
            "חוזה הספרייה השתנה, ראו _install_token_ceiling"
        )
    state.tokens = capped


def _build_parser() -> MarkdownIt:
    """המופע היחיד.

    **מה כן רץ כאן בזמן ייבוא:** הגדרה, ועוד פרסור חימום אחד של מסמך
    בן שורה — ראו את הנימוק בסוף ה-docstring. אין רשת, אין דיסק, אין
    תהליכון ואין ``os.environ``, כלומר אף אחד מהטריגרים של
    ``import-time-side-effects``. והכלל ההוא אינו מסתפק בכך שהאובייקט
    מותר: הוא דורש שמה שהאובייקט **מפעיל** בזמן היצירה ייבדק לגופו —
    ולכן המחיר נמדד, והוא 0.03–0.04 מילישניות (0.06–0.07 בלי החימום מול
    0.09–0.11 איתו, חציון של 1,000 בניות; markdown-it-py 4.2.0, עם כלל תקרת
    הטוקנים, 2026-09-27). זה נאמר במפורש כי
    "הגדרה בלבד" כבר **אינו** מדויק, ומשפט שמתיישן הוא בדיוק מה
    שמונע מהקורא הבא לבדוק.

    שלוש החלטות, וכל אחת נמדדה:

    1. **``commonmark`` כבסיס**, ולא ``gfm-like``: הוא מדליק בדיוק את
       מה שנמדד כנחוץ, במקום להדליק הכול ולקוות. ההרחבה היחידה שנוספת
       מעליו היא ``table`` — ראו (4).
    2. **``front_matter_plugin``** במקום סימון ידני של הבלוק. זו
       ההגדרה ש-MyST משתמש בה, ולכן היא הכלל שקובע מהו front matter גם
       בקובצי ה-``.md`` שתחת ``docs/`` בריפו הזה. נמדד שהיא **אינה מזיזה
       אף מספר שורה** באף אחת מעשר הצורות שנבדקו — כולל בלוק שאינו נסגר,
       ``---`` מוזח, ו-``---`` עם רווח בסוף — כי הטקסט עצמו אינו משתנה
       כלל. וכלל שהיינו כותבים בעצמנו כן היה סוטה ממנה: נמדד שהכלל שנכתב
       ביד ב-``scripts/generate_ai_map.py`` חלק עליה בחמש מתוך שתים-עשרה
       צורות. מאז #3419 הסקריפט קורא את הגבול מהמופע הזה, דרך
       :func:`front_matter_end`, והטבלה ב-``tests/test_md_parser.py``
       מקבעת שהשניים מסכימים על כל צורה.
    3. **``disable("inline")``** — הכלל ה**ליבתי** בשם הזה, שהוא זה
       שמפרק את תוכן הכותרת לטוקנים פנימיים. נמדד: עד 40% חיסכון בזמן
       ו-37% בזיכרון, **ואפס שינוי בזיהוי הכותרות ובטווחים** — כי השם
       נלקח מ-``token.content``, שהוא הטקסט הגולמי מהמקור בשני המצבים.
    4. **``enable("table")``** — הפריסט ``commonmark`` משאיר אותו כבוי,
       וזו **הרחבת ה-GFM היחידה שמזיזה כותרת**.

       בלעדיו, שורת טבלה שאחריה ``---`` או ``===`` **צמודים** אינה טבלה
       אלא פסקה, והקו שאחריה הופך אותה לכותרת setext: נמדד על
       ``| a | b |`` / ``|---|---|`` / ``| 1 | 2 |`` / ``---`` שנוצר סעיף
       ברמה 2 שכותרתו היא **הטבלה כולה**, והסעיף שמעליה נגמר לפני
       הטבלה במקום אחריה — כלומר ``section_text`` שלו כבר אינו מכיל
       אותה. עם הכלל, הפלט זהה בדיוק ל-cmark-gfm.

       **וארבע ההרחבות האחרות נבדקו ואינן משנות דבר**, ולכן הן נשארות
       כבויות: ``strikethrough`` ו-``autolink`` הן inline בלבד,
       ``tagfilter`` נוגע ברינדור ולא בפרסור, ו-``tasklist`` משנה פריט
       רשימה ולא גבול בלוק. הערות שוליים אינן ברשימה כלל —
       ``cmarkgfm.github_flavored_markdown_to_html`` מפעיל חמש הרחבות
       בדיוק (``table``, ``autolink``, ``tagfilter``, ``strikethrough``,
       ``tasklist``), ולכן ``[^1]: note`` הוא הגדרת קישור בשני הצדדים.

    ``before("front_matter", ...)`` ולא ``before("table", ...)``: הוא
    מציב את התקרה ראשונה בשרשרת. **והעוגן הזה נכשל ב-``KeyError`` אם
    התוסף לא נרשם על השרשרת** — כלומר מי שיסיר את ``.use(...)`` וישאיר
    את השורה הזאת ייפול כאן, מיד, ולא בשקט בזמן פרסור. ‏(תלות **חסרה**
    היא מקרה אחר והיא נופלת מוקדם יותר, בייבוא שבראש הקובץ.)

    **תקרת הטוקנים יושבת בשרשרת אחרת — ``core``, לפני ``block``** — כי היא
    אינה כלל בלוק: הכלל :func:`_install_token_ceiling` מחליף את רשימת הטוקנים
    לפני שהפרסור מתחיל, והבדיקה עצמה רצה בכל ``append`` (:class:`_CappedTokens`).
    העוגן ``"block"`` הוא הכלל שמריץ את כל הפרסור, ולכן אינו יכול להיעדר.

    **ופרסור החימום שבסוף אינו קישוט.** ``markdown-it`` בונה את רשימת
    הכללים של כל ruler **עצלה**, בקריאה הראשונה ל-``getRules``, בלי
    מנעול — ו-``Ruler.__compile__`` מפרסם מילון ריק לפני שהוא ממלא
    אותו. שלוש הקריאות למעלה רק מבטלות את המטמון ואינן בונות אותו
    מחדש, ולכן בלי החימום המופע מתפרסם כשחלק ממנו עדיין ייבנה — בפרסור
    הראשון, שהוא בדיוק הרגע שבו כמה חוטים יכולים להיות עליו יחד.

    **חימום, ולא מניית ה-rulers בשמם:** רשימת שמות מתיישנת ברגע שגרסה
    עתידית מוסיפה ruler למסלול, ואז החלון נפתח שוב בלי שאיש יידע.
    פרסור עובר באותו מסלול שפרסור אמיתי עובר בו, ולכן הוא מקמפל בדיוק
    את מה שנצרך — לא פחות, וגם לא rulers שממילא אינם בשימוש. נמדד:
    ``md.parse("")`` **אינו** מספיק, כי הוא משאיר את ``block.ruler`` לא
    מקומפל; מסמך עם כותרת אחת מקמפל את ``core`` ואת ``block``, שהם
    בדיוק שני ה-rulers שפרסור אמיתי מתייעץ איתם (``inline`` מכובה).
    ``tests/test_md_parser.py::test_every_ruler_a_real_parse_uses_is_compiled_before_publish``
    מקבע את זה: הוא מרגל אחרי ``getRules`` ונכשל אם החימום פספס ruler.
    """
    md = MarkdownIt("commonmark").use(front_matter_plugin).disable("inline").enable("table")
    md.block.ruler.before("front_matter", "ck_max_sections", _ceiling_rule)
    md.core.ruler.before("block", "ck_max_tokens", _install_token_ceiling)
    # בלי ``env``, ולכן ``state.env`` הוא מילון ריק: ``_ceiling_rule`` מקבל
    # ``None`` ומחזיר ``False`` מיד, ו-``_install_token_ceiling`` אינו מוצא
    # רשימה ואינו עושה דבר — החימום אינו משאיר שום מצב. **והוא נשאר השורה
    # האחרונה לפני ה-``return``**, אחרי כל קריאת תצורה (ראו למעלה).
    md.parse("# ck warm-up\n")
    return md


#: ההצבה עצמה אטומית, ולכן אף חוט אינו רואה כאן ``_MD`` חצי-בנוי.
#:
#: **וזה בדיוק מה שהטעה כאן קודם.** ל-``lazy-init-guard-publish-order``
#: יש פטור מפורש ל"מצב שנבנה כולו לפני שהוא מתפרסם — בנייה במשתנים
#: מקומיים, הצבה אחת", והשורות האלה נראות כמוהו בדיוק. אבל הפטור נבדק
#: על הקוד שלנו בלבד, ובפועל **האובייקט שפרסמנו בונה חלק מעצמו
#: בעצלתיים**: ``markdown-it`` מקמפל את רשימת הכללים של כל ruler רק
#: בקריאה הראשונה ל-``getRules``, ו-``__compile__`` מפרסם מילון **ריק**
#: לפני שהוא ממלא אותו כלל-כלל. זה סעיף 2 בכלל, "פרסום לפני אימות":
#: המשתנה שנבדק הוא אמנם זה שמוחזר, אבל הוא מתפרסם לפני שהערך שבו שלם.
#: ‏(**לא** סעיף 4 — שם מדובר במסלול מהיר מחוץ לנעילה, וכאן אין מנעול
#: בכלל, מה שמרחיב את החלון ולא מצמצם אותו.) הלקח: "בניתי לפני
#: שפרסמתי" חייב להיות נכון **גם על מה שבפנים**, ולא רק על ההצבה שלנו.
#:
#: מה שסוגר את זה הוא פרסור החימום ב-``_build_parser``, וההנמקה המלאה
#: שם. נמדד לפני ואחרי, ראו את גוף ה-PR.
_MD = _build_parser()


def _entry_checks(text: object) -> str:
    """שער הכניסה המשותף לכל מי שמפרסר כאן: ``parse_document``, ``token_count`` ו-``front_matter_end``.

    שלושה צעדים, בסדר הזה (ההנמקה לסדר ב-docstring של ``parse_document``):
    ``require_str``, הסרת BOM אחד בתחילת המחרוזת, ו-``\\r`` בודד →
    :class:`~services.doc_sections.InconsistentLineEndings`. הנרמול של
    ``\\r\\n`` נשאר ב-``parse_document``, כי רק היא בונה ``lines`` שחייב להסכים
    עם המפה; markdown-it מנרמל אותו בעצמו לפני הפרסור.

    עד סקירת שבעת ה-PRים (SUGG-019) שתי הפונקציות הקטנות קראו ל-``_MD.parse``
    ישירות ודילגו על שלושתם, ונמדד מה זה עושה: ``front_matter_end`` על בלוק
    שיש בו ``\\r`` בודד החזיר 4 בעוד ה-``---`` הסוגר יושב באינדקס 2 של
    ``split("\\n")`` — markdown-it סופר ``\\r`` כמעבר שורה והקורא לא — ועם BOM
    החזיר 0, כלומר לא ראה את הבלוק כלל; ערך שאינו מחרוזת נפל עם ההודעה של
    markdown-it ולא של המודול.
    """
    text = require_str(text)
    # **BOM אחד בתחילת הקובץ מוסר, ולא יותר מזה.** בלי ההסרה, ``# Title``
    # שלפניו ``U+FEFF`` אינו כותרת אצל ``markdown-it`` — הוא פסקה שמתחילה
    # בתו בלתי נראה — והפארסר מחזיר **מפה ריקה בלי חריגה** על קובץ שיש
    # בו כותרות, שזו בדיוק מחלקת הכשל שהמודול הזה מצהיר שאין בו. נמדד.
    #
    # **וזה יישור ל-cmark-gfm ול-GitHub, לא למפרט.** מימוש הייחוס של
    # CommonMark (``commonmark.py`` 0.9.2) **אינו** מסיר BOM ומרנדר
    # ``<p>﻿# Title</p>`` בדיוק כמו ``markdown-it``; cmark מסיר.
    # האורקל שנבחר למודול הזה הוא GitHub, ולכן הולכים אחריו.
    #
    # **למה זה אינו מזיז מספרי שורות:** התו יושב בעמודה 0 של שורה 1
    # ואינו מעבר שורה, ולכן ``lines`` ומספרי המפה זהים עם ובלי ההסרה —
    # אותו תנאי שהתיר את נרמול ה-``\r\n``. חיתוך בתווים, לא בבייטים.
    #
    # **ורק בתחילת המחרוזת.** ``U+FEFF`` באמצע הטקסט הוא ZERO WIDTH
    # NO-BREAK SPACE רגיל — תוכן, לא סימון קידוד — ואיש אינו נוגע בו.
    # מסלול הייצור (``git_mirror_service._try_decode_content``) מפענח
    # ב-``utf-8-sig`` ולכן לא יעביר BOM לכאן; ההגנה היא בשביל כל קורא
    # אחר — הסקריפט, טסט, או הצרכן הבא — שיפענח ב-``utf-8`` רגיל.
    if text.startswith("﻿"):
        text = text[1:]
    # **החריגה נושאת את מספר השורה**, כמו ``TooManySections``. המיקום
    # כבר מחושב כאן — ``search`` מחזיר אובייקט התאמה — והוא ההבדל בין
    # "יש ``\r`` איפשהו בקובץ" לבין משהו שאפשר לפתוח ולתקן.
    lone_cr = find_lone_cr(text)
    if lone_cr:
        raise InconsistentLineEndings(text.count("\n", 0, lone_cr.start()) + 1)
    return text


def token_count(text: str) -> int:
    """מספר הטוקנים שהפרסר של הכלי מייצר לטקסט — מדד צפיפות, לא מפה.

    קיים בשביל ``scripts/measure_md_parse_cost.py``, שמדרג מסמכים לפי
    צפיפות טוקני-בלוק ל-KB, וקרא עד #3433 ל-``_build_parser`` הפרטית —
    תלות סמויה בפנימי של המודול, ובנייה של פרסר חדש לכל קובץ. הפונקציה
    הזאת היא התלות בגלוי: על ``_MD``, המופע שהכלי מריץ, בלי ``env`` ולכן
    בלי אף תקרה — לא של כותרות (``_ceiling_rule`` מקבל ``None`` ומחזיר
    ``False``), לא של טוקנים (``_install_token_ceiling`` אינו מוצא רשימה) ולא
    של שורות — ובלי טוקני inline (``disable("inline")``), כלומר בדיוק מה
    שהפרסור האמיתי סופר. **בלי תקרות בכוונה:** המדד צריך לספור גם מעל
    :data:`MAX_TOKENS`, כדי לומר כמה רחוק קובץ נמצא ממנה, והוא רץ רק בסקריפטים
    על קבצי הריפו ולא על קלט של משתמש. ודרך אותו שער כניסה
    (:func:`_entry_checks`): BOM מוסר, ``\\r`` בודד נדחה, וערך שאינו מחרוזת
    מקבל את החריגה של המודול — כמו בכלי.

    **ומחוץ ל-``__all__`` בכוונה:** הרשימה שם היא החוזה של "שני פארסרים
    בני-החלפה", וטסט מקבע את ההפרש בינה לבין זו של ``rst_parser``. מדד
    למדידה אינו חלק מהחוזה הזה ואינו קיים ל-RST, ולכן הוא ציבורי (בלי קו
    תחתון, מתועד) אך אינו מיוצא.
    """
    return len(_MD.parse(_entry_checks(text)))


def parse_document(
    text: str,
    *,
    max_sections: Optional[int] = MAX_SECTIONS,
    max_lines: Optional[int] = MAX_LINES,
    max_tokens: Optional[int] = MAX_TOKENS,
) -> Document:
    """בונה ``Document`` מטקסט Markdown.

    **סדר הבדיקות בכניסה, והוא אינו שרירותי:**

    1. :func:`~services.doc_sections.require_str` — הטקסט מגיע מחוץ
       לתהליך (קובץ מהמראה, גוף בקשה), ו-``.replace`` על ערך שאינו מחרוזת
       היה מפיל ``AttributeError`` ממקום שלא מסביר כלום. אותה בדיקה
       בדיוק, ואותן מילים, כמו ב-``rst_parser`` (מאז #3421).
    2. הסרת ``U+FEFF`` (BOM) **אחד, בתחילת המחרוזת בלבד** — ההנמקה
       בהערה ליד הקוד ב-:func:`_entry_checks`, השער המשותף לשלוש הפונקציות
       שמפרסרות כאן. לפני בדיקת ה-``\\r``, כדי שמספר השורה שהחריגה
       נושאת יתאים לטקסט שהפארסר באמת רואה.
    3. ``\\r`` בודד → :class:`~services.doc_sections.InconsistentLineEndings`.
    4. **תקרת השורות** → :class:`~services.doc_sections.TooManyLines`. אחרי
       שלב 3, כי רק שם ספירת השורות חד-משמעית; ולפני כל העתקה, פיצול או
       פרסור, כי אלה בדיוק העבודה שגדלה עם מספר השורות.
    5. נרמול ``\\r\\n`` ← ``\\n``. ``splitlines()`` נשקל ונדחה באותו
       נימוק שכתוב ב-``rst_parser``: הוא מפצל על עשרה תווים במקום אחד.
    6. סימון ה-front matter — בתוך הפרסור, על ידי התוסף.
    7. פרסור, עם **תקרת הטוקנים** שנבדקת בכל טוקן שנוצר
       (:class:`~services.doc_sections.TooManyTokens`), ותקרת הכותרות בתחילת
       כל בלוק ובשער שאחרי הפרסור.

    **שני הנרמולים — הסרת ה-BOM ו-``\\r\\n`` ← ``\\n`` — הם היחידים
    שמותרים, ומאותו תנאי בדיוק:** אף אחד מהם אינו משנה כמה שורות יש,
    ולכן ``lines`` ומספרי השורות במפה נשארים מיושרים.

    **ה-front matter מטופל בתוך הפרסור ולא לפניו**, ולכן הוא שלב 6 ולא
    שלב שלפני הבדיקות. אילו היינו מחליפים את שורות הבלוק לפני שלב 3,
    הוא היה יכול לבלוע ``\\r`` בודד שיושב בתוכו, ולהסתיר בדיוק את
    הקלט ששלב 3 קיים בשבילו.

    :param max_sections: התקרה, **במספר כותרות ולא במספר סעיפים** —
        ראו :data:`~services.doc_sections.MAX_SECTIONS`. ברירת המחדל היא
        :data:`~services.doc_sections.MAX_SECTIONS` — אותה ברירת מחדל
        כמו ב-``services.rst_parser.parse_document`` (מיושר מאז #3420;
        לפני כן היא הייתה ``None`` שם, וההבדל היה מוצהר בשני המקומות) —
        ו-``None`` מכבה אותה במפורש. עם שתי התקרות האחרות על ברירת המחדל
        שלהן היא אינה יכולה להיפגע — ראו את ה-docstring של המודול.
    :param max_lines: התקרה על מספר השורות, ביחידה של ``count_lines`` —
        ראו :data:`MAX_LINES`. ``None`` מכבה אותה במפורש.
    :param max_tokens: התקרה על מספר טוקני הבלוק — ראו :data:`MAX_TOKENS`.
        ``None`` מכבה אותה במפורש.

    :raises TypeError: ``text`` אינו מחרוזת.
    :raises ~services.doc_sections.InconsistentLineEndings: יש ``\\r``
        שאינו חלק מ-``\\r\\n``.
    :raises ~services.doc_sections.TooManyLines: יש בקלט יותר שורות מהתקרה.
        החריגה נושאת את מספר השורות ואת התקרה, והפרסור לא התחיל.
    :raises ~services.doc_sections.TooManyTokens: הפרסור הגיע לתקרת הטוקנים.
        החריגה נושאת את השורה שבה הפרסור היה ואת התקרה.
    :raises ~services.doc_sections.TooManySections: הקלט מכיל יותר
        כותרות מהתקרה. הארגומנט הוא מספר השורה שבה נעצרנו — מה שמבדיל
        עצירה בתוך הפרסור מסינון של פלט אחריו.
    """
    text = _entry_checks(text)

    # **תקרת השורות — לפני כל עבודה שגדלה עם מספר השורות.** ``replace``,
    # ``split`` והמערכים ש-``StateBlock`` בונה לכל שורה הם בדיוק העלות שהתקרה
    # קיימת כדי לחסום, ולכן הספירה רצה על ``text`` עצמו. ``\r\n`` אינו משנה
    # אותה (כל אחד נושא ``\n`` אחד בדיוק), ו-``\r`` בודד כבר נדחה בשלב הקודם.
    # הנוסחה היא זו של ``count_lines`` ב-``mcp_server/handlers.py`` — ראו
    # :data:`MAX_LINES`.
    total_lines = text.count("\n") + 1 if text else 0
    if max_lines is not None and total_lines > max_lines:
        raise TooManyLines(total_lines, max_lines)

    normalized = text.replace("\r\n", "\n")
    lines = normalized.split("\n")

    env: dict = {}
    if max_sections is not None:
        env[_ENV_COUNTER] = _SectionCounter(max_sections)
    capped: Optional[_CappedTokens] = None
    if max_tokens is not None:
        capped = _CappedTokens(max_tokens)
        env[_ENV_TOKENS] = capped

    tokens = _MD.parse(normalized, env)

    # **המעקה של תקרת הטוקנים — הרשימה שחזרה היא זו שהותקנה.** ההתקנה עוברת
    # בכלל core ולא בבנאי של ``StateCore``, כי שם רשימה ריקה נבלעת בשקט
    # (``tokens or []``); והבדיקה כאן היא מה שהופך כל החלפה עתידית — שינוי
    # בספרייה, כלל נוסף, או מסלול התקנה אחר — מפרסור שרץ בלי תקרה ונראה כמו
    # פרסור עם תקרה, לכשל בקול. ``is`` ולא ``isinstance``: השאלה היא אם זו
    # **אותה** רשימה, ולא אם יש איפשהו רשימה מאותו סוג.
    if capped is not None and tokens is not capped:
        raise RuntimeError(
            "תקרת הטוקנים לא נאכפה: markdown-it החזיר רשימה אחרת מזו שהותקנה — "
            "ראו _install_token_ceiling"
        )

    # **שער שני לאותה תקרה, ולא כפילות.** הכלל שבתוך הפרסור נקרא
    # ב**תחילת** כל בלוק, ולכן הטוקנים שנדחפו אחרי הקריאה האחרונה שלו
    # אינם נסרקים — כלומר קלט שחוצה את התקרה בכותרת האחרונה ממש היה
    # חומק. זה בדיוק התקדים שכבר קיים במסלול ה-RST, שם ``add_section``
    # ו-``Capped.append`` שומרים על אותו מספר משני צדדים.
    #
    # **וזו סריקה אחרונה של אותו מונה, ולא ספירה שנייה של משהו אחר.**
    # בדיקה על ``len(sections)`` הייתה סופרת סעיפים בזמן שהכלל שבפנים
    # סופר כותרות, ואז שני השערים מודדים שני דברים — נמדד שקלט של
    # כותרות בתוך ציטוט, שהאחרונה בהן היא הבלוק האחרון, חומק בין
    # השניים בלי שום סירוב. ``scan`` מדלג על מה שכבר נסרק, ולכן
    # הקריאה הזאת היא רק השארית.
    counter: Optional[_SectionCounter] = env.get(_ENV_COUNTER)
    if counter is not None and counter.scan(tokens):
        # הארגומנט הוא **סוף הקובץ** ולא שורת הכותרת החורגת, וזה מכוון:
        # זה המקום שאליו הפרסור באמת הגיע לפני שסירב. מספר שהיה מצביע על
        # הכותרת עצמה היה נראה זהה לעצירה בתוך הפרסור, ואז הטענה "נעצרנו
        # באמצע" לא הייתה ניתנת לבדיקה — נמדד בבדיקת מוטציה שבדיוק זה קרה.
        raise TooManySections(len(lines))

    sections = _sections_from_tokens(tokens, total_lines=len(lines))
    _finalize(sections, len(lines))
    return Document(lines=lines, sections=sections)


def _sections_from_tokens(tokens: List[Token], *, total_lines: int) -> List[Section]:
    """הסעיפים שבמפה, לפי הכללים שהוכרעו במדידה.

    **רק ``token.level == 0``.** כותרת בתוך ציטוט או בתוך פריט רשימה
    **מזוהה** ככותרת — הפארסר אינו מתווכח עם GitHub — אבל אינה סעיף
    במסמך: היא חלק מהמכל שלה. ו**הטווח שלה שבור מעצם ההגדרה**, כי
    ``end_line`` נמתח עד הכותרת הבאה באותה רמה או גבוהה ממנה, כלומר
    הרבה מעבר לסוף הציטוט. נמדד: ברמת המסמך ``level`` הוא ``0``, בתוך
    ציטוט ``1``, בתוך פריט רשימה ``2``, ובקינון עמוק יותר — יותר.

    **וה-``end_line`` כאן זמני.** ``token.map`` מכסה את שורת הכותרת
    בלבד — ``(1, 1)`` ל-ATX ו-``(1, 3)`` ל-setext רב-שורתי — ואינו יודע
    דבר על גוף הסעיף. החישוב האמיתי הוא של ``_finalize`` המשותף, וזו
    הסיבה שהוא לא נכתב כאן מחדש.
    """
    sections: List[Section] = []
    for index, token in enumerate(tokens):
        if token.type != "heading_open" or token.level != 0:
            continue
        # ``is None`` ולא בדיקה בוליאנית: ``map`` הוא שדה של אובייקט
        # SDK, והצורה הזאת נכונה תמיד.
        #
        # **וזו אינה נפילה-לאחור, היא הרמה.** דילוג שקט כאן היה מפיל
        # סעיף בלי לוג, בלי מטריקה ובלי חריגה — כלומר "לא נמצא" ו"נשבר"
        # נראים זהים לקורא, בדיוק הצורה שהמודול הזה מצהיר שאין בו. אומת
        # מול ``rules_block/heading.py`` ו-``lheading.py``: כל מסלול
        # שדוחף ``heading_open`` מציב ``map`` ללא תנאי, ולכן הענף אינו
        # ניתן להגעה היום — והרמה כאן פירושה שהספרייה שינתה חוזה.
        #
        # ``RuntimeError`` ולא ``AssertionError``: האחרונה מסמנת שבירת
        # הנחה פנימית, והמטפל שימפה חריגות לתשובת MCP יזהה טיפוסים
        # מוכרים. **וזה אינו ערוץ סירוב נוסף** — ערוצי הסירוב הם אלה שמנויים
        # ב-docstring של המודול (``TypeError`` וחריגות הסירוב של
        # ``doc_sections``), וזה כאן הוא שגיאה פנימית שאין למשתמש מה לעשות איתה.
        if token.map is None:
            raise RuntimeError(
                f"markdown-it דחף heading_open בלי map בשורה {index} — "
                "חוזה הספרייה השתנה, ראו _sections_from_tokens"
            )
        start = token.map[0] + 1
        sections.append(
            Section(
                title=_title_of(tokens, index),
                level=int(token.tag[1:]),
                title_line=start,
                heading_line=start,
                end_line=total_lines,
                adornment=token.markup,
                over=False,
            )
        )
    return sections


def _title_of(tokens: List[Token], heading_index: int) -> str:
    """טקסט הכותרת, גולמי מהמקור — למעט הרווחים שאינם חלק ממנו.

    עם ``inline`` כבוי, ``token.content`` של הטוקן שאחרי ה-``heading_open``
    הוא **כמעט** הטקסט כפי שנכתב: ה-``#`` וקו ה-setext מוסרים, הרווחים
    מסביב מקוצצים, וכל הסימון נשמר — בקטיקים, הדגשה, קישורים, ו-``\\#``
    שעבר escape. **הסימון נשאר בכוונה**, וזו ההכרעה המקורית: הכותרת היא
    מה שכתוב בקובץ.

    **ומה שכן מנורמל כאן, ולמה זה לא סותר את זה.** בכותרת setext
    רב-שורתית, ``content`` נושא גם את ההזחה של שורות ההמשך ואת הרווחים
    בסוף כל שורה — ושני אלה **אינם טקסט הכותרת אצל אף אחד**. נמדד:
    ‏``"aaa\\n    bbb\\n===\\n"`` מרונדר ל-``<h1>aaa\\nbbb</h1>`` גם
    ב-``markdown-it-py`` עצמה וגם ב-cmark-gfm, ואילו ``content`` הגולמי
    הוא ``"aaa\\n    bbb"``. כלומר ההזחה שורדת אצלנו **רק** מפני
    ש-``inline`` מכובה — היא ארטיפקט של אופטימיזציה, לא החלטה.

    הכלל שמיושם כאן הוא בדיוק זה של ``rules_inline/newline.py``, שהוא
    הכלל שהיה רץ אילו ``inline`` היה דלוק: ``rstrip`` של **רווחים בלבד**
    בסוף כל שורה שאינה האחרונה (שם גם ``"  \\n"`` של hardbreak מתקפל),
    ו-``lstrip`` של רווח **או טאב** בתחילת כל שורה שאינה הראשונה —
    ‏``isStrSpace`` שם הוא ``("\\t", " ")`` ותו לא. ההתאמה נבדקת מול
    cmark-gfm ב-``tests/test_md_parser_oracle.py::_compare_titles``.

    השארית המכוונת: ה-``\\n`` **עצמו** בין השורות נשמר, כי הוא כן חלק
    מהכותרת. ``normalize_title`` מכווץ אותו לרווח, ולכן חיפוש בשורה אחת
    מוצא כותרת שנפרסת על שתיים.
    """
    following = tokens[heading_index + 1] if heading_index + 1 < len(tokens) else None
    if following is None or following.type != "inline":
        return ""
    content = following.content.strip()
    if "\n" not in content:
        # המסלול של ATX ושל setext בשורה אחת — הרוב המוחלט, ובלי עבודה.
        return content
    parts = content.split("\n")
    last = len(parts) - 1
    return "\n".join(
        (part if index == 0 else part.lstrip(" \t")).rstrip(" ") if index < last
        else (part if index == 0 else part.lstrip(" \t"))
        for index, part in enumerate(parts)
    )


def front_matter_end(text: str) -> int:
    """אינדקס השורה שאחרי בלוק ה-front matter — או 0 כשאין בלוק, כולל בלוק שלא נסגר.

    לפי התוסף ``mdit_py_plugins.front_matter`` שרשום על ``_MD`` — ההגדרה
    ש-MyST מריץ — ולא לפי כלל שנכתב ביד. ``scripts/generate_ai_map.py`` כתב
    עד #3419 כלל משלו, ונמדד שהוא חלק על התוסף בחמש מתוך שתים-עשרה צורות:
    ``---`` מוזח, סוגר מוזח בארבעה רווחים, ארבעה מקפים, סוגר ארוך מהפותח,
    ופותח שיש אחריו טקסט. הטוקן ``front_matter`` הוא תמיד הראשון (התוסף
    מזהה בלוק רק בשורה 0) ונושא ``map = [0, end]``, ו-``end`` הוא בדיוק
    האינדקס שהסקריפט צריך.

    פרסור מלא של הטקסט, בלי ``env`` ולכן בלי אף תקרה (לא כותרות, לא טוקנים
    ולא שורות) — הקלט הוא קבצים מהריפו: עמודי תיעוד ב-
    ``scripts/generate_ai_map.py``, והקורפוס ב-``scripts/md_parser_upgrade_zero_diff.py``.
    ודרך :func:`_entry_checks`, כי האינדקס שמוחזר חייב להסכים עם
    ``split("\\n")`` של הקורא: ``\\r`` בודד (ש-markdown-it סופר כמעבר שורה)
    היה מזיז אותו בשקט, ו-BOM היה מסתיר את הבלוק כולו — עכשיו הראשון
    נדחה בשם, והשני מוסר, בדיוק כמו ב-``parse_document``. **מחוץ ל-``__all__``
    בכוונה**, מאותו נימוק שכתוב ליד :func:`token_count` אם הוא קיים כאן:
    הרשימה שם היא החוזה של "שני פארסרים בני-החלפה", וגבול front matter אינו
    קיים ל-RST.
    """
    tokens = _MD.parse(_entry_checks(text))
    if tokens and tokens[0].type == "front_matter" and tokens[0].map:
        return tokens[0].map[1]
    return 0
