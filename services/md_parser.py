"""פארסר Markdown שבונה את מודל הסעיפים המשותף שב-``doc_sections``.

מודול תאום ל-``services/rst_parser.py``: אותו ``Document``, אותם
``Section``, ואותן פונקציות עץ — ולכן ``mcp_server/docs_handlers.py``
יוכל לבחור פארסר לפי סיומת ולהמשיך זהה בית-בית. כל מה שאינו תלוי-שפה
נקרא מ-``doc_sections`` ואינו נכתב כאן מחדש, ובכלל זה חישוב ה-``end_line``
וההיררכיה.

**למה ``markdown-it-py`` ולא פארסר משלנו.** נמדד מול cmark-gfm — הפארסר
ש-GitHub מריץ בפועל — על **18,216 צורות מחוללות**: אפס אי-הסכמות, למעט
הפערים הידועים והמקובעים — **2,450 צורות** בסך הכול — שיושבים בטבלה אחת,
``tests/test_md_parser_oracle.py::_KNOWN_DIVERGENCES``. כל שורה שם היא סיבה ולא
רשימת מופעים, והם אינם מתוקנים כאן. לכל שורה: הסיבה, צורה לדוגמה ומה כל צד
מחזיר עליה, על מה ומתי נמדדה. התיעוד מעתיק ממנה (:ref:`mcp-md-known-divergences`
ב-``docs/mcp-server.rst``), וטסט משווה בכל שורה את הסיבה, את "N מתוך M", את
הגרסאות והתאריך ואת הקישור ל-upstream.
שני המספרים אינם מוקלדים כאן ביד אלא נגזרים מהמחוללים ומהטבלה, ומושווים
למה שכתוב בשורות האלה
ב-``tests/test_md_parser_oracle.py::test_the_generated_shape_count_matches_the_prose``,
כדי שתוספת משפחת צורות, או שורה בטבלה, בלי עדכון המשפט הזה תפיל את
החבילה.

ובנוסף, על קורפוס אמיתי — **97 קבצים ו-1,240 כותרות, אפס אי-הסכמות, ואפס
שורות שמפעילות פער ידוע שיש לו טריגר**. רק לחלק מהשורות בטבלה יש טריגר, והנימוק
כתוב ליד כל שורה שאין לה. המספר הזה **אינו מקובע בטסט** כי הוא תלוי בריפו
חיצוני שמשתנה, ולכן הוא מתוארך במקום: נמדד ב-27 בספטמבר 2026 על
``amir-bug-patterns`` בקומיט ``456e90b``, על markdown-it-py 4.2.0, והפקודה
שמפיקה אותו היא ``python scripts/compare_md_parser_to_cmark.py <נתיב לריפו>``.
מי שירצה לאמת יריץ אותה, ולא יסתמך על המספר.

פארסר שנכתב ביד היה
צריך להוכיח את השקילות הזאת מחדש בכל שינוי, והסורק ל-RST שכן נכתב ביד
עבר ארבעה סבבי סקירה שכל אחד מהם מצא מה שקודמו פספס. המחיר מוצהר: הוא
איטי פי 10–25 מ-cmark-gfm, וזה נסבל בשכבה שחלה כאן.

**שלוש תקרות, ולכל אחת תפקיד שהאחרות אינן ממלאות** (#3391):

* **שורות** (:data:`MAX_LINES`) — לפני הפרסור. חלק מהזיכרון של
  ``markdown-it-py`` נגזר ממספר השורות ולא ממספר הטוקנים, ולכן קובץ שכולו
  שורות ריקות, או ציטוט מקונן לעומק, אינו נראה לאף תקרה אחרת.
* **טוקנים** (:data:`MAX_TOKENS`) — ברגע שנוצר כל טוקן, ולכן גם באמצע טבלה
  ובאמצע רשימה.
* **כותרות** (``max_sections``, :data:`~services.doc_sections.MAX_SECTIONS`) —
  בתחילת כל בלוק. **ב-Markdown היא אינה יכולה להיפגע עם ברירות המחדל:** כל
  כותרת צריכה שורה משלה, ו-:data:`MAX_LINES` קטן מ-``MAX_SECTIONS``. היא
  נשארת בשביל ``rst_parser`` (אותו חוזה), ובשביל מתקשר שמעביר תקרה קטנה
  במפורש.

**מה שהמודול הזה לא עושה, כדי שהקורא לא ישלים מהדמיון:**

* **אין דה-דופליקציה של כותרות ואין נרמול של טקסט הכותרת.** השם מוחזר
  כפי שהוא במקור, עם בקטיקים, הדגשות וקישורים.
* **אין ``includes``** — לצורה הזאת אין מקבילה ב-Markdown, והשדה נשאר ריק.

**ערוץ הכשל הוא חריגה בלבד.** ``parse_document`` אף פעם אינו מחזיר
``None``, ``Document`` חלקי, או מפה ריקה כדי לסמן כשל: קובץ בלי כותרות
מחזיר מפה ריקה **תקינה**, וכל סירוב הוא חריגה — ``TypeError``,
``InconsistentLineEndings``, ``TooManyLines``, ``TooManyTokens`` או
``TooManySections``. זה נכתב במפורש כי פונקציה עם שני ערוצי כשל היא בדיוק
מה שמלכד את הקורא הבא.
"""

