"""מה נחשב קובץ Markdown שמור — כלל אחד, לוובאפ ולשרת ה-MCP.

**הכלל:** שם השפה (``programming_language``) הוא ``markdown`` או ``md``, **או**
ששם הקובץ נגמר ב-``.md`` או ב-``.markdown`` — בלי תלות ברישיות, ומספיק אחד
מהשניים. זה הכלל שלפיו הוובאפ מחליט אם להציג קובץ כ-Markdown (תצוגה מקדימה,
ייצוא HTML מעוצב, מצב קריאה), וזה הכלל שלפיו ``codekeeper_get_file`` מחליט אם
אפשר לקרוא קובץ לפי סעיף (``section=`` / ``toc=true``).

**למה מודול משלו.** עד PR ג של "קריאה לפי סעיף" הכלל ישב ב-``_is_markdown_file``
ב-``webapp/app.py``, ועוד שני עותקים שלו היו כתובים בגוף מסלולי השמירה של
הוובאפ (איסוף התמונות של Markdown). ה-MCP אינו מייבא מהוובאפ ואינו תלוי ב-Flask,
ועותק רביעי שלו בשרת ה-MCP היה בדיוק ``duplicate-rule-second-copy`` (R6): ביום
שאחד יורחב — ``.mdx``, למשל — המפה של הסוכן והתצוגה של המשתמש היו חולקות על
אותו קובץ בלי שאיש יידע. אותו תקדים כמו ``services/line_endings.py``: הגדרה אחת
ב-``services``, ושני הצרכנים קוראים לה.

**ומה הכלל הזה אינו**, כי בריפו יש שלושה כללים אחרים עם שם דומה ומשמעות אחרת,
והם **לא** אוחדו כאן:

- ``is_markdown_filename`` (``src/domain/services/code_normalizer.py``) — לפי
  השם בלבד, עם חמש סיומות (``MARKDOWN_SUFFIXES`` של ``language_detector``), כדי
  להחליט על ניקוי קוד מודבק בבוט.
- הבוט (``handlers/file_view.py``) — מחליט איך להציג קובץ בטלגרם, ושם ``md`` אינו
  שם שפה.
- תיקוני השפה בוובאפ (למשל ``text`` עם ``.md`` שהופך ל-``markdown`` לפני
  ההחלטה) — הם מתקנים את השפה ואינם מחליטים דבר; הכלל כאן כבר מכסה את התוצאה
  שלהם, כי הסיומת לבדה מספיקה.

**מודול טהור:** בלי I/O, ובזמן ייבוא לא רץ כלום מלבד הגדרות — ולכן גם שרת
ה-MCP, שמודולי החבילה שלו מייבאים רק תלויות קלות ברמת המודול, יכול לייבא אותו.
"""

from __future__ import annotations

#: שמות השפה שהופכים קובץ ל-Markdown, בכתיב המנורמל (אותיות קטנות).
MARKDOWN_LANGUAGES = frozenset({"markdown", "md"})

#: הסיומות שהופכות קובץ ל-Markdown, בכתיב המנורמל. **הנקודה היא חלק מהסיומת,
#: וזה הגבול.** ``endswith(".md")`` אינו ``endswith("md")``: שם שנגמר ב-``.amd``
#: אינו נתפס, כי מה שנבדק הוא הרכיב שאחרי הנקודה ולא רצף תווים — אותו עיקרון
#: של ``K16`` ב-amir-bug-patterns (גבול מפורש ולא קידומת של מחרוזת).
MARKDOWN_FILE_SUFFIXES = (".md", ".markdown")


def is_markdown_file(language: object, file_name: object) -> bool:
    """האם קובץ שמור הוא Markdown, לפי שם השפה **או** לפי סיומת השם.

    שני השדות מגיעים ממסמך במסד, ולכן נבדקים כ-``str`` לפני ``lower()``: ערך
    שאינו מחרוזת (``None``, מספר) פשוט אינו מעיד על Markdown, ואינו מפיל את
    הקורא. **אין כאן ``strip``**, בכוונה: הכלל של הוובאפ לא קיצץ רווחים מעולם,
    וקוראים שמקצצים — כמו מסך התצוגה המקדימה — עושים זאת לפני הקריאה.
    """
    if isinstance(language, str) and language.lower() in MARKDOWN_LANGUAGES:
        return True
    return isinstance(file_name, str) and file_name.lower().endswith(MARKDOWN_FILE_SUFFIXES)
